static int g_pass = 0;
static int g_fail = 0;

static void check(bool ok, const string& msg) {
    if (ok) {
        ++g_pass;
    } else {
        ++g_fail;
        std::cout << "  [FAIL] " << msg << "\n";
    }
}

static void check_close(double got, double want, double tol, const string& msg) {
    double denom = std::max(std::abs(got), std::abs(want));
    double rel = denom > 0.0 ? std::abs(got - want) / denom : std::abs(got - want);
    if (!(rel <= tol)) {
        std::cout << "  [FAIL] " << msg << " (got " << got << ", want " << want
                  << ", rel " << rel << ")\n";
        ++g_fail;
    } else {
        ++g_pass;
    }
}

