// 3. THE GRADIENT MATCHES THE ORACLE'S
// =============================================================================

static void test_gradient_matches_oracle() {
    std::cout << "[3] the gradient matches the oracle's\n";

    for (const Fixture& f : FX) {
        OrdinalRegression layer(f.D, f.K);
        configure(layer, f);

        Tensor x = fixture_x(f);
        Tensor logp = layer.forward(x);
        Tensor g = nll_grad_output(f.N, f.K, f.labels);
        layer.zero_grad();
        layer.backward(g, 0.0);

        Tensor gb = layer.beta_gradient();
        Tensor gr = layer.cut_gradient();
        for (size_t d = 0; d < f.D; ++d) {
            check_close(gb[0][d], f.gbeta[d], 1e-9,
                        string(f.name) + ": dL/dbeta[" + std::to_string(d) +
                        "] vs the oracle");
        }
        for (size_t k = 0; k + 1 < f.K; ++k) {
            check_close(gr[0][k], f.graw[k], 1e-9,
                        string(f.name) + ": dL/draw[" + std::to_string(k) +
                        "] vs the oracle");
        }
    }
}

// =============================================================================
// 4. THE GRADIENT MATCHES AN INDEPENDENT CENTRAL FINITE DIFFERENCE
//    (computed here, in the test, on the objective -- NOT on the formula).
// =============================================================================

static void test_gradient_matches_finite_difference() {
    std::cout << "[4] the gradient matches an independent central finite difference\n";

    OrdinalRegression layer(3, 4);
    layer.set_beta(0, 0.7);
    layer.set_beta(1, -1.3);
    layer.set_beta(2, 0.45);
    layer.set_raw_cut(0, 0.25);
    layer.set_raw_cut(1, 0.8);
    layer.set_raw_cut(2, -0.15);

    Tensor x(3, 3);
    x[0][0] = 1.0;  x[0][1] = 0.5;  x[0][2] = -0.25;
    x[1][0] = -0.5; x[1][1] = 2.0;  x[1][2] = 0.75;
    x[2][0] = 0.25; x[2][1] = -1.0; x[2][2] = 1.5;
    const int labels[3] = {0, 2, 1};

    auto objective = [&](OrdinalRegression& lay) {
        Tensor lp = lay.forward(x);
        return mean_nll(lp, labels, 3);
    };

    const double h = 1e-6;

    // dL/dbeta
    Tensor g = nll_grad_output(3, 4, labels);
    layer.zero_grad();
    // forward() MUST run first: it is what caches the input that backward
    // differentiates against. Calling backward() on a layer whose forward()
    // has never run is a call-order bug, and the layer rejects it.
    layer.forward(x);
    layer.backward(g, 0.0);
    Tensor gb = layer.beta_gradient();

    for (size_t d = 0; d < 3; ++d) {
        double orig = layer.beta_at(d);
        layer.set_beta(d, orig + h);
        double lp = objective(layer);
        layer.set_beta(d, orig - h);
        double lm = objective(layer);
        layer.set_beta(d, orig);
        double fd = (lp - lm) / (2.0 * h);
        check_close(gb[0][d], fd, 1e-5,
                   "dL/dbeta[" + std::to_string(d) + "] vs the finite difference");
    }

    // dL/draw
    Tensor gr = layer.cut_gradient();
    for (size_t k = 0; k < 3; ++k) {
        double orig = layer.raw_cut_at(k);
        layer.set_raw_cut(k, orig + h);
        double lp = objective(layer);
        layer.set_raw_cut(k, orig - h);
        double lm = objective(layer);
        layer.set_raw_cut(k, orig);
        double fd = (lp - lm) / (2.0 * h);
        check_close(gr[0][k], fd, 1e-5,
                   "dL/draw[" + std::to_string(k) + "] vs the finite difference");
    }
}

// =============================================================================
// 5. THE CUT POINTS ARE ORDERED BY CONSTRUCTION, AND THE GAPS ARE NOT
//    RECOVERED BY DIFFERENCING (the absorption trap).
// =============================================================================

static void test_ordering_is_structural() {
    std::cout << "[5] the ordering is structural and the gaps are not differenced\n";

    // A hostile set of raw parameters: wildly out of order, and one that
    // would make the cumulative sum absorb a gap.
    OrdinalRegression layer(2, 3);
    layer.set_raw_cut(0, 100.0);
    layer.set_raw_cut(1, -100.0);

    Tensor theta = layer.cut_points();
    check(theta.rows == 1 && theta.cols == 2, "cut_points() must be (1, K-1)");
    check(theta[0][1] >= theta[0][0],
          "the cut points must be non-decreasing (they are structural)");

    // THE ABSORPTION TRAP: theta_1 = 100 with a gap of softplus(-100) is
    // 3.7e-44, and the cumulative sum theta_2 = 100 + 3.7e-44 rounds to
    // EXACTLY 100. Differencing the cut points would report a gap of 0.
    // The layer must keep the gap.
    //
    // NOTE THE PRECISE INVARIANT: the FLOAT64 CUT POINTS MAY COLLIDE (that
    // is a limit of the representation), but the MODEL'S GAP DOES NOT. The
    // oracle's own F4 fixture records THETA = {100, 100} -- the collision is
    // expected, and the gap is recovered from the raw parameter.
    Tensor gaps = layer.cut_gaps();
    check(gaps.rows == 1 && gaps.cols == 1, "cut_gaps() must be (1, K-2)");
    check(gaps[0][0] > 0.0,
          "the gap must be strictly positive even where the float64 cut "
          "points collide");
    // softplus(-100) = 3.7200759760208361e-44. Compared ABSOLUTELY: the
    // oracle's own F4 fixture carries the same value, and a relative
    // comparison against a hand-rounded "3.7e-44" would be measuring the
    // rounding of the literal, not the computation.
    check(std::abs(gaps[0][0] - 3.7200759760208361e-44) <= 1e-56,
          "the gap must be softplus(-100) = 3.72008e-44, NOT the 0 that "
          "differencing the cut points would report");
    check(theta[0][1] == theta[0][0],
          "the float64 cut points are EXPECTED to collide on this fixture "
          "(the oracle's F4 fixture records THETA = {100, 100})");

    Tensor x(1, 2);
    x[0][0] = 1.0;
    x[0][1] = 0.0;

    Tensor logp = layer.forward(x);
    // The interior class's log probability must reflect the tiny gap:
    // log(1 - e^{-gap}) with gap = 3.7e-44 is about -99.9, NOT -inf and NOT
    // the value a zero gap would give.
    check(std::isfinite(logp[0][1]),
          "the interior class log probability must be finite on the "
          "absorption fixture");
    check(logp[0][1] < -50.0,
          "the interior class log probability must reflect the tiny gap "
          "(it must be very negative, not ~0)");

    // And the layer's own reported cut points must still be non-decreasing.
    Tensor t2 = layer.cut_points();
    check(t2[0][1] >= t2[0][0], "the cut points must be non-decreasing");
}

// =============================================================================
// 6. MONOTONICITY IN THE LATENT SCORE (the defining property)
// =============================================================================

static void test_monotonicity_in_eta() {
    std::cout << "[6] a higher latent score moves mass towards higher classes\n";

    OrdinalRegression layer(1, 3);
    layer.set_beta(0, 1.0);
    layer.set_raw_cut(0, 0.0);
    layer.set_raw_cut(1, std::log(std::exp(1.0) - 1.0));

    double prev_expected = -1e300;
    for (double eta = -4.0; eta <= 4.0; eta += 1.0) {
        Tensor x(1, 1);
        x[0][0] = eta;
        Tensor logp = layer.forward(x);
        double expected = 0.0;
        double prev_cum = 0.0;
        for (size_t k = 0; k < 3; ++k) {
            double p = std::exp(logp[0][k]);
            expected += static_cast<double>(k) * p;
            double cum = prev_cum + p;
            // P(Y <= k) must DECREASE as eta rises.
            (void)cum;
            prev_cum = cum;
        }
        // expected_class() must agree with the hand computation.
        Tensor e = layer.expected_class(x);
        check_close(e[0][0], expected, 1e-12,
                    "expected_class must agree with sum_k k*P_k");

        check(expected > prev_expected,
              "the expected class must strictly increase with eta");
        prev_expected = expected;
    }
}

// =============================================================================
// 7. THE COMPOSITION WITH THE REPO'S OWN NLLLoss
//    (utils/losses.h) -- the layer's log probabilities feed it directly.
// =============================================================================

static void test_composes_with_nll_loss() {
    std::cout << "[7] the layer composes with the repo's NLLLoss\n";

    OrdinalRegression layer(2, 3);
    layer.set_beta(0, 0.7);
    layer.set_beta(1, -1.3);
    layer.set_raw_cut(0, 0.25);
    layer.set_raw_cut(1, 0.8);

    Tensor x(2, 2);
    x[0][0] = 1.0;  x[0][1] = 0.5;
    x[1][0] = -0.5; x[1][1] = 2.0;

    Tensor targets(2, 1);
    targets[0][0] = 0.0;
    targets[1][0] = 2.0;

    Tensor logp = layer.forward(x);

    NLLLoss loss(Reduction::Mean);
    Tensor l = loss.forward(logp, targets);
    check(l.rows == 1 && l.cols == 1, "NLLLoss must return a scalar");

    // The value must equal the oracle's mean NLL for F1.
    check_close(l[0][0], ORC_F1_NLL, 1e-11,
                "the composed NLL vs the oracle's mean NLL");

    // And the gradient path must compose: NLLLoss::backward gives dL/d(log P),
    // which is exactly what the layer's backward consumes.
    Tensor grad_out(1, 1);
    grad_out[0][0] = 1.0;
    Tensor dlogp = loss.backward(logp, targets, grad_out);
    layer.zero_grad();
    layer.backward(dlogp, 0.0);
    Tensor gb = layer.beta_gradient();
    for (size_t d = 0; d < 2; ++d) {
        check_close(gb[0][d], ORC_F1_GRAD_BETA[d], 1e-9,
                    "the composed gradient vs the oracle's");
    }
}

// =============================================================================
// 8. A TRAINING STEP REDUCES THE LOSS (the end-to-end liveness check)
// =============================================================================

static void test_training_reduces_the_loss() {
    std::cout << "[8] training reduces the loss\n";

    OrdinalRegression layer(2, 3);
    Tensor x(4, 2);
    Tensor targets(4, 1);
    const double xs[4][2] = {{1.0, 0.5}, {-0.5, 2.0}, {0.25, -1.0}, {2.0, 0.25}};
    const int ys[4] = {0, 2, 1, 2};
    for (size_t i = 0; i < 4; ++i) {
        x[i][0] = xs[i][0];
        x[i][1] = xs[i][1];
        targets[i][0] = static_cast<double>(ys[i]);
    }

    NLLLoss loss(Reduction::Mean);
    Tensor grad_out(1, 1);
    grad_out[0][0] = 1.0;

    auto current_loss = [&]() {
        Tensor lp = layer.forward(x);
        return loss.forward(lp, targets)[0][0];
    };

    double l0 = current_loss();
    for (int step = 0; step < 200; ++step) {
        Tensor lp = layer.forward(x);
        Tensor dlogp = loss.backward(lp, targets, grad_out);
        layer.zero_grad();
        layer.backward(dlogp, 0.0);
        layer.update_weights(0.5);
    }
    double l1 = current_loss();
    check(l1 < l0,
          "training must reduce the loss (" + std::to_string(l0) + " -> " +
          std::to_string(l1) + ")");

    // LIVENESS: the layer must not be dead. Its parameters must have MOVED
    // away from their initial values -- a network whose readout is frozen
    // reduces the loss only through the bias.
    bool moved = false;
    for (size_t d = 0; d < 2; ++d) {
        if (std::abs(layer.beta_at(d)) > 1e-12) moved = true;
    }
    for (size_t k = 0; k < 2; ++k) {
        if (std::abs(layer.raw_cut_at(k) - (k == 0 ? 0.0 : 0.0)) > 1e-12) moved = true;
    }
    check(moved, "the parameters must have MOVED (a dead layer reduces the "
                 "loss only through a frozen readout)");
}

// =============================================================================
// 9. THE EDGE CASES: K = 2 (a single cut point), and the argument guards.
// =============================================================================

static void test_edge_cases() {
    std::cout << "[9] the edge cases and the argument guards\n";

    // K = 2: exactly one cut point, so there is no interior class and no
    // gap at all. The probabilities must still sum to 1.
    OrdinalRegression binary(1, 2);
    binary.set_beta(0, 1.0);
    binary.set_raw_cut(0, 0.0);
    Tensor x(1, 1);
    x[0][0] = 0.5;
    Tensor logp = binary.forward(x);
    check(logp.rows == 1 && logp.cols == 2, "K=2 must give (N, 2)");
    double total = std::exp(logp[0][0]) + std::exp(logp[0][1]);
    check_close(total, 1.0, 1e-12, "K=2 probabilities must sum to 1");
    // P(Y=0) = sigmoid(theta_1 - eta), P(Y=1) = 1 - that.
    double expect0 = 1.0 / (1.0 + std::exp(-(0.0 - 0.5)));
    check_close(std::exp(logp[0][0]), expect0, 1e-12,
                "K=2 class 0 probability");

    // The cut points of a K=2 model: exactly one.
    Tensor th = binary.cut_points();
    check(th.rows == 1 && th.cols == 1, "K=2 must have exactly one cut point");

    // A class index outside [0, K) must be REJECTED, not silently clamped.
    bool threw = false;
    try {
        OrdinalRegression bad(1, 2);
        bad.set_raw_cut(0, 0.0);
        bad.set_raw_cut(1, 0.0);   // there is no second cut point for K=2
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "setting a cut point out of range must throw");

    bool threw2 = false;
    try {
        OrdinalRegression bad(1, 2);
        bad.set_beta(3, 0.0);     // there is only one feature
    } catch (const std::exception&) {
        threw2 = true;
    }
    check(threw2, "setting a slope out of range must throw");

    // THE INPUT-WIDTH GUARD. A mismatched input must be REJECTED, not read
    // past the end of the weight row. This is a memory-safety guard, not a
    // politeness check: without it the dot product reads past the end of
    // beta_ and the layer returns garbage silently.
    bool threw3 = false;
    try {
        OrdinalRegression wide(2, 3);
        wide.set_raw_cut(0, 0.0);
        wide.set_raw_cut(1, 0.0);
        Tensor bad_x(1, 3);       // 3 features into a 2-feature layer
        bad_x[0][0] = 1.0;
        bad_x[0][1] = 0.0;
        bad_x[0][2] = 0.0;
        wide.forward(bad_x);
    } catch (const std::exception&) {
        threw3 = true;
    }
    check(threw3, "a mismatched input width must throw");

    // And the TOO-NARROW case, which is the one that would read PAST the
    // end of the buffer if the guard were one-sided.
    bool threw4 = false;
    try {
        OrdinalRegression narrow(2, 3);
        narrow.set_raw_cut(0, 0.0);
        narrow.set_raw_cut(1, 0.0);
        Tensor bad_x(1, 1);       // 1 feature into a 2-feature layer
        bad_x[0][0] = 1.0;
        narrow.forward(bad_x);
    } catch (const std::exception&) {
        threw4 = true;
    }
    check(threw4, "a too-narrow input must throw too");

    // The constructor's own guards.
    bool threw5 = false;
    try {
        OrdinalRegression one_class(1, 1);   // K must be at least 2
    } catch (const std::exception&) {
        threw5 = true;
    }
    check(threw5, "K < 2 must throw at construction");

    bool threw6 = false;
    try {
        OrdinalRegression no_features(0, 3);
    } catch (const std::exception&) {
        threw6 = true;
    }
    check(threw6, "D == 0 must throw at construction");
}

