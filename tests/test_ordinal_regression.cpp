// The mean ordinal NLL, computed from the layer's log probabilities. This is
// the objective the oracle's gradients are the gradient of.
static double mean_nll(const Tensor& log_probs, const int* labels, size_t n) {
    double total = 0.0;
    for (size_t i = 0; i < n; ++i) {
        total += -log_probs[i][labels[i]];
    }
    return total / static_cast<double>(n);
}

// d(mean NLL) / d(log P) -- the upstream gradient the layer's backward
// consumes. It is -1/N at the observed class and zero elsewhere.
static Tensor nll_grad_output(size_t n, size_t k, const int* labels) {
    Tensor g(n, k);
    g.fill(0.0);
    for (size_t i = 0; i < n; ++i) {
        g[i][labels[i]] = -1.0 / static_cast<double>(n);
    }
    return g;
}

