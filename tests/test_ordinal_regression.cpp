// Build the (N, D) input tensor from the flat fixture row-major data.
static Tensor fixture_x(const Fixture& f) {
    Tensor x(f.N, f.D);
    for (size_t i = 0; i < f.N; ++i)
        for (size_t d = 0; d < f.D; ++d)
            x[i][d] = f.x[i * f.D + d];
    return x;
}

// Configure a layer from a fixture's parameters.
static void configure(OrdinalRegression& layer, const Fixture& f) {
    for (size_t d = 0; d < f.D; ++d) layer.set_beta(d, f.beta[d]);
    for (size_t k = 0; k + 1 < f.K; ++k) layer.set_raw_cut(k, f.raw[k]);
}

static void test_forward_matches_oracle() {
    std::cout << "[1] forward matches the oracle's LOG probabilities\n";

    for (const Fixture& f : FX) {
        OrdinalRegression layer(f.D, f.K);
        configure(layer, f);

        Tensor x = fixture_x(f);
        Tensor logp = layer.forward(x);
        check(logp.rows == f.N && logp.cols == f.K,
              string(f.name) + ": forward shape must be (N, K)");
        for (size_t i = 0; i < f.N; ++i) {
            for (size_t k = 0; k < f.K; ++k) {
                check_close(logp[i][k], f.logp[i * f.K + k], 1e-11,
                            string(f.name) + " row " + std::to_string(i) +
                            " class " + std::to_string(k) +
                            ": log P vs the oracle");
            }
        }
    }
}

// =============================================================================
// 2. THE PROBABILITIES SUM TO ONE, ARE NON-NEGATIVE, AND THE CUMULATIVE IS
//    MONOTONE. (The naive difference of two cumulatives would violate all
//    three on the F3/F5/F6 fixtures.)
// =============================================================================

static void test_probabilities_are_a_distribution() {
    std::cout << "[2] the probabilities form a distribution\n";

    OrdinalRegression layer(2, 3);
    layer.set_beta(0, -30.0);
    layer.set_beta(1, -10.0);
    layer.set_raw_cut(0, 0.0);
    layer.set_raw_cut(1, std::log(std::exp(1.0) - 1.0));

    Tensor x(1, 2);
    x[0][0] = 1.0;
    x[0][1] = 1.0;

    Tensor logp = layer.forward(x);
    double total = 0.0;
    double prev_cum = 0.0;
    for (size_t k = 0; k < 3; ++k) {
        double p = std::exp(logp[0][k]);
        check(p >= 0.0, "the probability must be non-negative");
        check(std::isfinite(p), "the probability must be finite");
        total += p;
        double cum = prev_cum + p;
        check(cum >= prev_cum - 1e-15, "the cumulative must be non-decreasing");
        prev_cum = cum;
    }
    check_close(total, 1.0, 1e-12, "the probabilities must sum to 1");

    // THE POINT OF FINDING 1: the naive difference of two cumulatives is
    // EXACTLY 0 for the interior class on this fixture, while the true
    // probability is 2.685e-18. The layer must NOT produce 0.
    double interior = std::exp(logp[0][1]);
    check(interior > 0.0,
          "the interior class probability must be strictly positive "
          "(the naive difference of two cumulatives is exactly 0 here)");
    check_close(interior, 2.6854720659566001e-18, 1e-9,
                "the interior class probability vs the oracle");
}

