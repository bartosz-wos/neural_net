// THE SPECIFICATION IS tests/ordinal_regression_oracle.py (float64 numpy +
// scipy + 60-digit decimal), which was written and run BEFORE this file
// existed. Its discriminating power was MEASURED, not narrated:
// tests/ordinal_regression_mutate_oracle.py breaks the oracle in ten specific
// ways and requires that it fail each time (10 caught / 0 survived).
//
// The oracle found FOUR defects in its own first drafts, all of which changed
// the specification:
//   1. the stable closed form was missing the e^{-v} factor;
//   2. the 60-digit softplus had `1 - exp(-t)` instead of `1 + exp(-t)`,
//      which produced NEGATIVE probabilities;
//   3. the analytic gradient was written in probability space, where the
//      c*(1-c) factor cancels catastrophically (analytic 0 vs FD -1);
//   4. the (u, gaps) reparameterisation credited a gap shift to ONE class.
// =============================================================================
//
// THE FOUR THINGS THAT ARE EASY TO GET WRONG
//
//  1. THE PROBABILITY OF AN INTERIOR CLASS IS A DIFFERENCE OF TWO
//     CUMULATIVES, AND THE NAIVE DIFFERENCE LOSES ALL OF IT. With eta = -40
//     both sigmoids round to exactly 1.0 and the difference is EXACTLY 0.0,
//     while the true probability is 2.685e-18.
//
//  2. THE SAME CANCELLATION SITS INSIDE THE GRADIENT, WHICH IS WHY THE
//     LAYER OUTPUTS LOG PROBABILITIES. The probability-space derivative
//     carries c*(1-c), which is exactly 0 where c has rounded to 1.0, while
//     the true derivative is about -1.
//
//  3. THE ORDERING IS STRUCTURAL (softplus increments), AND THE GAPS MUST
//     NOT BE RECOVERED BY DIFFERENCING THE THETAS: the cumulative sum can
//     absorb a tiny gap, so differencing reports a gap of 0.
//
//  4. THE INTERIOR CLASSES' PROBABILITY DEPENDS ON THE *SPREAD* OF TWO CUT
//     POINTS, not only their positions -- the q term -- and the q term
//     CANCELS between the two theta-partials, so it must be differentiated
//     in (u, gaps) coordinates.
//
// THE PINNED FIXTURES ARE TRANSFERRED FROM THE ORACLE, NOT HAND-TRANSCRIBED.
// The repo has been burned by hand-transcribed numbers before (see
// tests/_dump_fixture.py): both numbers were CORRECT for the fixture they
