// Build a tensor from a flat array.
//
// A NULL `data` means ZERO-FILL. The first draft of this file passed
// nullptr at three call sites (intending an all-zero tensor) and the helper
// dereferenced it unconditionally -- a SEGFAULT in the harness, caught by
// gdb's backtrace at make_tensor -> test_intercept_only_fit. The guard is
// here so that a zero-filled fixture cannot be misread as a crash in the
// layer.
static Tensor make_tensor(size_t rows, size_t cols, const double* data) {
    Tensor t(rows, cols);
    for (size_t i = 0; i < rows; ++i)
        for (size_t j = 0; j < cols; ++j)
            t[i][j] = (data == nullptr) ? 0.0 : data[i * cols + j];
    return t;
}

static vector<double> to_vector(const vector<double>& v) { return v; }

