static int g_pass = 0;
static int g_fail = 0;

static void check(bool ok, const string& msg) {
    if (ok) {
        ++g_pass;
    } else {
        ++g_fail;
        std::cout << "  [FAIL] " << msg << "\n";
    }
}

static void check_close(double got, double want, double tol, const string& msg) {
    double denom = std::max(std::abs(got), std::abs(want));
    double rel = denom > 0.0 ? std::abs(got - want) / denom : std::abs(got - want);
    if (!(rel <= tol)) {
        std::cout << "  [FAIL] " << msg << " (got " << got << ", want " << want
                  << ", rel " << rel << ")\n";
        ++g_fail;
    } else {
        ++g_pass;
    }
}

// Does `fn` throw an exception whose MESSAGE contains `needle`?
//
// THE MESSAGE, NOT THE THROW. The mutation harness caught this: a test that
// asserts only "it threw" passes even when the guard it means to cover is
// GONE, because a DIFFERENT guard (or a downstream dimension check) throws
// instead. The discriminator is the message.
//
// The message is read AFTER the call, so it belongs to the call under test
// -- an argument-evaluation-order trap that would otherwise print the
// PREVIOUS call's message beside the current verdict.
static bool throws_with(const std::function<void()>& fn, const string& needle) {
    try {
        fn();
    } catch (const std::exception& e) {
        return string(e.what()).find(needle) != string::npos;
    }
    return false;
}

