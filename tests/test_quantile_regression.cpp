static void test_loss_and_gradient_match_oracle() {
    std::cout << "-- Test 3: the loss and gradient match the oracle\n";

    QuantileRegression layer(ORC_F2_D, to_vector({0.1, 0.5, 0.9}));
    for (size_t k = 0; k < ORC_F2_K; ++k) {
        for (size_t d = 0; d < ORC_F2_D; ++d) {
            layer.set_weight_at(k, d, ORC_F2_W[k * ORC_F2_D + d]);
        }
        layer.set_bias_at(k, ORC_F2_B[k]);
    }
    Tensor X = make_tensor(ORC_F2_N, ORC_F2_D, ORC_F2_X);
    Tensor y = make_tensor(ORC_F2_N, 1, ORC_F2_Y);
    Tensor pred = layer.forward(X);

    Tensor loss = layer.pinball_loss(pred, y);
    check(loss.rows == 1 && loss.cols == 1,
          "pinball_loss returns a (1, 1) tensor");
    check_close(loss[0][0], ORC_F2_LOSS, 1e-13,
                "the multi-level loss matches the oracle");

    Tensor grad = layer.pinball_gradient(pred, y);
    check(grad.rows == ORC_F2_N && grad.cols == ORC_F2_K,
          "pinball_gradient returns (N, K)");
    for (size_t i = 0; i < ORC_F2_N; ++i) {
        for (size_t k = 0; k < ORC_F2_K; ++k) {
            check_close(grad[i][k], ORC_F2_GRAD[i * ORC_F2_K + k], 1e-13,
                        "the multi-level gradient matches the oracle");
        }
    }

    // The backward pass must reproduce the oracle's parameter gradients.
    layer.zero_grad();
    Tensor gx = layer.backward(grad, 0.0);
    check(gx.rows == ORC_F2_N && gx.cols == ORC_F2_D,
          "backward returns dL/d(input) with shape (N, D)");
    Tensor gw = layer.weight_gradient();
    Tensor gb = layer.bias_gradient();
    for (size_t k = 0; k < ORC_F2_K; ++k) {
        for (size_t d = 0; d < ORC_F2_D; ++d) {
            check_close(gw[k][d], ORC_F2_GRADW[k * ORC_F2_D + d], 1e-13,
                        "dL/dW matches the oracle");
        }
        check_close(gb[0][k], ORC_F2_GRADB[k], 1e-13,
                    "dL/db matches the oracle");
    }
    for (size_t i = 0; i < ORC_F2_N; ++i) {
        for (size_t d = 0; d < ORC_F2_D; ++d) {
            check_close(gx[i][d], ORC_F2_GRADX[i * ORC_F2_D + d], 1e-13,
                        "dL/d(input) matches the oracle");
        }
    }
}

// =============================================================================
// TEST 4: the gradient matches central finite differences
//
// THE PINBALL OBJECTIVE IS PIECEWISE LINEAR IN THE PARAMETERS, so a central
// difference that does not cross a kink is EXACT up to roundoff. The check
// is therefore tight (~1e-9), not the loose 1e-4 a smooth objective would
// need.
//
// The residuals are all far from the kink, so no perturbation crosses one.
// =============================================================================

static void test_gradient_matches_finite_difference() {
    std::cout << "-- Test 4: the gradient matches central finite differences\n";

    QuantileRegression layer(ORC_F2_D, to_vector({0.1, 0.5, 0.9}));
    for (size_t k = 0; k < ORC_F2_K; ++k) {
        for (size_t d = 0; d < ORC_F2_D; ++d) {
            layer.set_weight_at(k, d, ORC_F2_W[k * ORC_F2_D + d]);
        }
        layer.set_bias_at(k, ORC_F2_B[k]);
    }
    Tensor X = make_tensor(ORC_F2_N, ORC_F2_D, ORC_F2_X);
    Tensor y = make_tensor(ORC_F2_N, 1, ORC_F2_Y);

    // The residuals must be far from the kinks, or the FD would straddle one
    // and the comparison would be meaningless.
    Tensor pred0 = layer.forward(X);
    double min_res = 1e300;
    for (size_t i = 0; i < ORC_F2_N; ++i)
        for (size_t k = 0; k < ORC_F2_K; ++k)
            min_res = std::min(min_res, std::abs(y[i][0] - pred0[i][k]));
    check(min_res > 1e-3,
          "every residual is far from the kink, so the FD check is valid");

    const double eps = 1e-6;

    // --- the weight gradient ---
    layer.zero_grad();
    Tensor grad = layer.pinball_gradient(pred0, y);
    layer.backward(grad, 0.0);
    Tensor gw = layer.weight_gradient();

    double worst_w = 0.0;
    for (size_t k = 0; k < ORC_F2_K; ++k) {
        for (size_t d = 0; d < ORC_F2_D; ++d) {
            const double orig = layer.weight_at(k, d);
            layer.set_weight_at(k, d, orig + eps);
            Tensor lp = layer.pinball_loss(layer.forward(X), y);
            layer.set_weight_at(k, d, orig - eps);
            Tensor lm = layer.pinball_loss(layer.forward(X), y);
            layer.set_weight_at(k, d, orig);
            double fd = (lp[0][0] - lm[0][0]) / (2.0 * eps);
            worst_w = std::max(worst_w, std::abs(fd - gw[k][d]));
        }
    }
    check(worst_w < 1e-8,
          "dL/dW matches the central finite difference (worst " +
              std::to_string(worst_w) + ")");

    // --- the bias gradient ---
    layer.zero_grad();
    layer.backward(layer.pinball_gradient(layer.forward(X), y), 0.0);
    Tensor gb = layer.bias_gradient();
    double worst_b = 0.0;
    for (size_t k = 0; k < ORC_F2_K; ++k) {
        const double orig = layer.bias_at(k);
        layer.set_bias_at(k, orig + eps);
        Tensor lp = layer.pinball_loss(layer.forward(X), y);
        layer.set_bias_at(k, orig - eps);
        Tensor lm = layer.pinball_loss(layer.forward(X), y);
        layer.set_bias_at(k, orig);
        double fd = (lp[0][0] - lm[0][0]) / (2.0 * eps);
        worst_b = std::max(worst_b, std::abs(fd - gb[0][k]));
    }
    check(worst_b < 1e-8,
          "dL/db matches the central finite difference (worst " +
              std::to_string(worst_b) + ")");

    // --- the input gradient ---
    layer.zero_grad();
    Tensor gx = layer.backward(layer.pinball_gradient(layer.forward(X), y), 0.0);
    double worst_x = 0.0;
    for (size_t i = 0; i < ORC_F2_N; ++i) {
        for (size_t d = 0; d < ORC_F2_D; ++d) {
            const double orig = X[i][d];
            X[i][d] = orig + eps;
            Tensor lp = layer.pinball_loss(layer.forward(X), y);
            X[i][d] = orig - eps;
            Tensor lm = layer.pinball_loss(layer.forward(X), y);
            X[i][d] = orig;
            double fd = (lp[0][0] - lm[0][0]) / (2.0 * eps);
            worst_x = std::max(worst_x, std::abs(fd - gx[i][d]));
        }
    }
    check(worst_x < 1e-8,
          "dL/d(input) matches the central finite difference (worst " +
              std::to_string(worst_x) + ")");
}

// =============================================================================
// TEST 5: the levels DECOUPLE -- the total loss separates into the per-level
// losses, which is what makes the classical independent fit possible.
//
// The k-th level's gradient must depend ONLY on the k-th column of the
// predictions. If the implementation mixed the columns, the total loss would
// no longer be the sum of K independent objectives and the estimator would
// no longer be the classical one.
// =============================================================================

static void test_levels_decouple() {
    std::cout << "-- Test 5: the levels decouple\n";

    QuantileRegression layer(ORC_F2_D, to_vector({0.1, 0.5, 0.9}));
    for (size_t k = 0; k < ORC_F2_K; ++k) {
        for (size_t d = 0; d < ORC_F2_D; ++d) {
            layer.set_weight_at(k, d, ORC_F2_W[k * ORC_F2_D + d]);
        }
        layer.set_bias_at(k, ORC_F2_B[k]);
    }
    Tensor X = make_tensor(ORC_F2_N, ORC_F2_D, ORC_F2_X);
    Tensor y = make_tensor(ORC_F2_N, 1, ORC_F2_Y);
    Tensor pred = layer.forward(X);

    Tensor grad = layer.pinball_gradient(pred, y);
    layer.zero_grad();
    layer.backward(grad, 0.0);
    Tensor gw = layer.weight_gradient();

    // The per-level gradient computed from the SINGLE-level loss must equal
    // the multi-level gradient's k-th column, and the k-th row of dL/dW.
    for (size_t k = 0; k < ORC_F2_K; ++k) {
        QuantileLoss single(layer.quantiles()[k]);
        Tensor col = layer.level_column(pred, k);
        Tensor g_single = single.backward(col, y);
        for (size_t i = 0; i < ORC_F2_N; ++i) {
            check_close(g_single[i][0], grad[i][k], 1e-13,
                        "the single-level gradient equals the multi-level "
                        "column");
        }
        // And the per-level slope gradient.
        for (size_t d = 0; d < ORC_F2_D; ++d) {
            double acc = 0.0;
            for (size_t i = 0; i < ORC_F2_N; ++i) acc += g_single[i][0] * X[i][d];
            check_close(acc, gw[k][d], 1e-13,
                        "the per-level dL/dW equals the single-level one");
        }
    }
}

// =============================================================================
// TEST 6: the crossing diagnostic and the monotone rearrangement
// =============================================================================

static void test_crossing_and_monotone() {
    std::cout << "-- Test 6: the crossing diagnostic and the monotone projection\n";

    QuantileRegression layer(3, to_vector({0.1, 0.5, 0.9}));

    // The constructed fixture: row 0 has one inversion (3 > 1), row 1 has one
    // (5 > 4), row 2 has none. So two adjacent inversions in total.
    Tensor p = make_tensor(3, 3, ORC_F3_PRED);
    check(layer.crossing_count(p) == 2,
          "the constructed fixture has exactly 2 adjacent inversions");
    Tensor m = layer.monotone(p);
    check(layer.crossing_count(m) == 0,
          "the rearrangement has no crossings");
    const double want[9] = {1, 2, 3, 0, 4, 5, 1, 2, 3};
    for (size_t i = 0; i < 3; ++i)
        for (size_t k = 0; k < 3; ++k)
            check_close(m[i][k], want[i * 3 + k], 1e-15,
                        "the rearrangement sorts each row ascending");

    // THE PROJECTION PRESERVES EACH ROW'S MULTISET: it may reorder, never
    // invent or destroy a value.
    bool multiset_ok = true;
    for (size_t i = 0; i < 3; ++i) {
        vector<double> a, b;
        for (size_t k = 0; k < 3; ++k) {
            a.push_back(p[i][k]);
            b.push_back(m[i][k]);
        }
        std::sort(a.begin(), a.end());
        std::sort(b.begin(), b.end());
        for (size_t k = 0; k < 3; ++k)
            if (a[k] != b[k]) multiset_ok = false;
    }
    check(multiset_ok, "the rearrangement preserves each row's multiset");

    // The projection is idempotent.
    Tensor m2 = layer.monotone(m);
    bool idem = true;
    for (size_t i = 0; i < 3; ++i)
        for (size_t k = 0; k < 3; ++k)
            if (m2[i][k] != m[i][k]) idem = false;
    check(idem, "the rearrangement is idempotent");

    // A row that is already ordered is left ALONE -- the projection must not
    // disturb a good fit.
    Tensor good = make_tensor(2, 3, ORC_F3_PRED);  // reuse storage, then set
    for (size_t i = 0; i < 2; ++i)
        for (size_t k = 0; k < 3; ++k) good[i][k] = (double)(i * 3 + k);
    Tensor mg = layer.monotone(good);
    bool unchanged = true;
    for (size_t i = 0; i < 2; ++i)
        for (size_t k = 0; k < 3; ++k)
            if (mg[i][k] != good[i][k]) unchanged = false;
    check(unchanged, "the rearrangement leaves an already-ordered row alone");
    check(layer.crossing_count(good) == 0,
          "an already-ordered row has no crossings");
}

// =============================================================================
// TEST 7: the HUNTED crossing fixture -- the crossing is REAL
//
// The oracle fitted the two levels INDEPENDENTLY (one pinball objective per
// level, exactly as the layer does) on a small dataset, and the resulting
// quantile LINES cross at x = 1.465. This test pins the crossing arithmetic
// on the real fitted coefficients, so the diagnostic is not exercised only on
// a hand-made fixture.
//
// The layer's own forward on the hunted x values must reproduce the fitted
// lines, and the two lines must actually cross.
// =============================================================================

static void test_hunted_crossing_is_real() {
    std::cout << "-- Test 7: the hunted crossing is real\n";

    QuantileRegression layer(1, to_vector({0.2, 0.8}));
    for (size_t k = 0; k < 2; ++k) {
        layer.set_weight_at(k, 0, ORC_F5_W[k]);
        layer.set_bias_at(k, ORC_F5_B[k]);
    }
    Tensor X = make_tensor(ORC_F5_N, 1, ORC_F5_X);
    Tensor pred = layer.forward(X);

    // At the crossing point the LOW level is ABOVE the high level.
    double lo_at_xc = ORC_F5_W[0] * ORC_F5_XC + ORC_F5_B[0];
    double hi_at_xc = ORC_F5_W[1] * ORC_F5_XC + ORC_F5_B[1];
    check(lo_at_xc > hi_at_xc,
          "the hunted levels really do cross at x = " +
              std::to_string(ORC_F5_XC));

    // THE CROSSING POINT LIES OUTSIDE THE FIXTURE'S x-RANGE, and that is a
    // real property of the fit, not an accident of the test: the levels were
    // fitted on the 8 sampled x values, and the two fitted LINES cross at
    // x = 1.4654, which is beyond every sampled x (the range is
    // [-0.979, 1.061]). So at each SAMPLED point the ordering still holds
    // and the diagnostic reports ZERO crossings there.
    //
    // This is the honest shape of the phenomenon: quantile crossing is a
    // statement about the fitted FUNCTIONS, and the diagnostic sees it at
    // the points where the functions are evaluated. A test that asserted
    // "the diagnostic fires on the fixture's own predictions" would be
    // asserting something false.
    check(ORC_F5_XC > ORC_F5_X[0] && ORC_F5_XC > ORC_F5_X[2],
          "the crossing point lies beyond the fixture's sampled x values");
    check(layer.crossing_count(pred) == 0,
          "at the SAMPLED points the ordering still holds, so the diagnostic "
          "reports no crossings");

    // Now evaluate BEYOND the crossing point, where the inversion is real.
    // The low level's slope exceeds the high level's, so past x_c the low
    // level is above the high one.
    const double x_beyond = ORC_F5_XC + 0.5;
    Tensor Xb(1, 1);
    Xb[0][0] = x_beyond;
    Tensor pred_beyond = layer.forward(Xb);
    check(pred_beyond[0][0] > pred_beyond[0][1],
          "beyond the crossing point the low level is above the high one");
    check(layer.crossing_count(pred_beyond) == 1,
          "the crossing diagnostic fires on the independently-fitted levels "
          "beyond the crossing point");

    // And the rearrangement repairs it.
    Tensor mono = layer.monotone(pred_beyond);
    check(layer.crossing_count(mono) == 0,
          "the rearrangement repairs the hunted crossing");
    check(mono[0][0] <= mono[0][1],
          "every repaired row is non-decreasing");

    // And the projection of the SAMPLED predictions is also non-decreasing.
    Tensor mono_all = layer.monotone(pred);
    check(layer.crossing_count(mono_all) == 0,
          "the rearrangement of the sampled predictions has no crossings");
    bool ordered = true;
    for (size_t i = 0; i < ORC_F5_N; ++i)
        for (size_t k = 0; k + 1 < 2; ++k)
            if (mono_all[i][k] > mono_all[i][k + 1]) ordered = false;
    check(ordered, "every repaired sampled row is non-decreasing");
}

// =============================================================================
// TEST 8: the intercept-only fit recovers the SAMPLE QUANTILE
//
// With X = 0 the prediction is the intercept alone, and the minimiser of the
// empirical pinball loss is the inverse-ECDF sample quantile. This is a
// DEFINITION-LEVEL target -- a quantity computed from the sample, not a
// re-run of the implementation.
//
// THE TOLERANCE IS DERIVED, NOT GUESSED: the oracle simulated the exact
// update the C++ performs and measured the steady-state oscillation at the
// tail of the trajectory (0.026 at lr = 0.5, 200 steps).
//
// AND THE LEARNING RATE IS NOT ARBITRARY: the oracle measured that at
// lr = 0.05 the fit has NOT arrived after 400 steps (tail deviation 1.91),
// because the intercept has to TRAVEL the gap between the sample values one
// step of size lr*|S - N*tau|/N at a time.
// =============================================================================

static void test_intercept_only_fit_recovers_the_sample_quantile() {
    std::cout << "-- Test 8: the intercept-only fit recovers the sample quantile\n";

    QuantileRegression layer(1, to_vector({0.05, 0.25, 0.75, 0.95}));
    Tensor X = make_tensor(ORC_F4_N, 1, nullptr);
    for (size_t i = 0; i < ORC_F4_N; ++i) X[i][0] = 0.0;
    Tensor y = make_tensor(ORC_F4_N, 1, ORC_F4_Y);

    // The loss must strictly DECREASE as the fit proceeds -- and the final
    // loss must be at most the loss at the closed-form target.
    double first_loss = 0.0;
    double last_loss = 0.0;
    for (int step = 0; step < ORC_F4_STEPS; ++step) {
        Tensor pred = layer.forward(X);
        Tensor loss = layer.pinball_loss(pred, y);
        if (step == 0) first_loss = loss[0][0];
        last_loss = loss[0][0];
        layer.zero_grad();
        Tensor grad = layer.pinball_gradient(pred, y);
        layer.backward(grad, 0.0);
        layer.update_weights(ORC_F4_LR);
    }
    check(last_loss < first_loss,
          "the intercept-only training reduces the loss (" +
              std::to_string(first_loss) + " -> " + std::to_string(last_loss) +
              ")");

    // Each level's intercept must have arrived at the closed-form sample
    // quantile, to the DERIVED tolerance.
    for (size_t k = 0; k < ORC_F4_K; ++k) {
        double got = layer.bias_at(k);
        check(std::abs(got - ORC_F4_TARGET[k]) <= ORC_F4_TOL,
              "level " + std::to_string(k) + ": the fitted intercept (" +
                  std::to_string(got) + ") is within the derived tolerance of "
                  "the sample quantile (" + std::to_string(ORC_F4_TARGET[k]) +
                  ")");
    }

    // And the final loss must be no worse than the loss at the target.
    Tensor pred_final = layer.forward(X);
    Tensor loss_final = layer.pinball_loss(pred_final, y);
    double loss_at_target = 0.0;
    for (size_t k = 0; k < ORC_F4_K; ++k)
        loss_at_target += ORC_F4_LOSS_AT_TARGET[k];
    // The TOTAL loss is the sum over the levels, and the oracle's per-level
    // figures are each the MEAN over the batch, so the comparable total is
    // their sum.
    check(loss_final[0][0] <= loss_at_target + 1e-9,
          "the trained loss is no worse than the loss at the closed-form "
          "quantiles");
}

// =============================================================================
// TEST 9: the composition with the shipped conformal machinery
//
// This is the gap the layer exists to close: `cqr_score` needs a lower and
// an upper quantile prediction, and until now nothing in the repo produced
// one.
//
// The composition is checked END TO END: the layer's output -> the monotone
// projection -> the CQR score -> the conformal quantile -> the prediction
// interval.
// =============================================================================

static void test_composes_with_conformal() {
    std::cout << "-- Test 9: the composition with the shipped conformal machinery\n";

    // A two-level layer at alpha/2 = 0.05 and 1 - alpha/2 = 0.95, which is
    // exactly the pair CQR wants.
    QuantileRegression layer(1, to_vector({0.05, 0.95}));
    // A fitted pair of lines: the lower one below the upper one.
    layer.set_weight_at(0, 0, 1.0);
    layer.set_bias_at(0, 0.0);
    layer.set_weight_at(1, 0, 1.0);
    layer.set_bias_at(1, 2.0);

    const size_t n = 20;
    Tensor X(n, 1);
    Tensor y(n, 1);
    for (size_t i = 0; i < n; ++i) {
        X[i][0] = 0.5;
        y[i][0] = 1.0;  // inside [0.5, 2.5]
    }

    Tensor pred = layer.forward(X);
    Tensor mono = layer.monotone(pred);
    Tensor lower = layer.level_column(mono, 0);
    Tensor upper = layer.level_column(mono, 1);
    check(lower.rows == n && lower.cols == 1,
          "level_column returns (N, 1) -- the shape cqr_score consumes");

    // The lower must not exceed the upper, which is what the crossing
    // projection buys.
    bool ordered = true;
    for (size_t i = 0; i < n; ++i)
        if (lower[i][0] > upper[i][0]) ordered = false;
    check(ordered, "the projected lower bound does not exceed the upper");

    // The CQR score.
    Tensor score = nn::utils::cqr_score(lower, upper, y);
    check(score.rows == n && score.cols == 1, "cqr_score returns (N, 1)");
    // The target is inside the interval, so the score is NEGATIVE -- which is
    // what lets CQR shrink the interval.
    check(score[0][0] < 0.0,
          "a target strictly inside the interval scores negative");

    // The conformal quantile and the prediction interval.
    Tensor scores = score.clone();
    double qhat = nn::utils::conformal_quantile(scores, 0.1);
    check(std::isfinite(qhat), "the conformal quantile is finite");
    double lo = lower[0][0], hi = upper[0][0];
    Tensor iv = nn::utils::cqr_interval(lo, hi, qhat);
    check(iv.rows == 1 && iv.cols == 2, "cqr_interval returns (1, 2)");
    check(iv[0][0] <= iv[0][1], "the prediction interval is not inverted");

    // **THE CQR INTERVAL IS [lower - qhat, upper + qhat], AND A NEGATIVE qhat
    // SHRINKS IT -- IT DOES NOT CONTAIN THE QUANTILE PAIR.**
    //
    // The first draft of this test asserted "the interval contains the
    // fitted quantile pair", which is FALSE for a target strictly inside the
    // interval: the score is then NEGATIVE (that negativity is exactly what
    // lets CQR shrink an over-wide interval), so `qhat` is negative and
    // `lower - qhat` is ABOVE `lower`. The shipped `cqr_interval` is
    // [lower - qhat, upper + qhat], and the composition works precisely
    // because a negative qhat moves both ends INWARD.
    check(qhat < 0.0,
          "the conformal quantile is negative, because every target is "
          "strictly inside the interval");
    check(iv[0][0] > lo,
          "the negative qhat moves the LOWER end inward (the interval "
          "shrinks)");
    check(iv[0][1] < hi,
          "the negative qhat moves the UPPER end inward (the interval "
          "shrinks)");
    check_close(iv[0][0], lo - qhat, 1e-12,
                "the interval's lower end is lower - qhat");
    check_close(iv[0][1], hi + qhat, 1e-12,
                "the interval's upper end is upper + qhat");

    // And the SHRUNK interval still contains the observed target -- which is
    // the coverage guarantee doing its job.
    check(iv[0][0] <= y[0][0] && y[0][0] <= iv[0][1],
          "the shrunk interval still contains the observed target");
}

// =============================================================================
// TEST 10: the edge cases and the guards
// =============================================================================

static void test_edge_cases() {
    std::cout << "-- Test 10: the edge cases and the guards\n";

    // --- the constructor guards ---
    bool threw = false;
    try {
        QuantileRegression bad(0, to_vector({0.5}));
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "D == 0 must throw at construction");

    threw = false;
    try {
        QuantileRegression bad(1, to_vector({}));
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "an empty level vector must throw at construction");

    threw = false;
    try {
        QuantileRegression bad(1, to_vector({0.0, 0.5}));
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "a level of exactly 0 must throw at construction");

    threw = false;
    try {
        QuantileRegression bad(1, to_vector({0.5, 1.0}));
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "a level of exactly 1 must throw at construction");

    threw = false;
    try {
        QuantileRegression bad(1, to_vector({0.5, 0.3}));
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "levels that are not strictly increasing must throw");

    threw = false;
    try {
        QuantileRegression bad(1, to_vector({0.5, 0.5}));
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "duplicate levels must throw");

    // A SINGLE level is legal.
    bool ok = true;
    try {
        QuantileRegression one(1, to_vector({0.5}));
    } catch (const std::exception&) {
        ok = false;
    }
    check(ok, "a single level is legal");

    // --- the runtime guards ---
    QuantileRegression layer(2, to_vector({0.1, 0.5, 0.9}));
    Tensor wrong_width(3, 3);
    // THE MESSAGE, NOT THE THROW. With the layer's own width guard removed,
    // the call still throws -- but from `Tensor::operator*`'s dimension
    // check, with the message "Tensor multiplication dimension mismatch".
    // A test that asserts only "it threw" therefore PASSES with the guard
    // removed, which is exactly the coverage hole the mutation harness
    // reported. The discriminator is the layer's OWN message.
    check(throws_with([&]() { layer.forward(wrong_width); }, "in_features"),
          "a wrong input width throws the LAYER'S OWN guard (its message "
          "names in_features), not a downstream dimension check");
    // And the downstream message is what a naive test would have accepted.
    check(!throws_with([&]() { layer.forward(wrong_width); },
                        "dimension mismatch"),
          "the wrong-width failure is not the Tensor dimension check");

    Tensor X(3, 2);
    Tensor pred = layer.forward(X);
    Tensor y_wrong_cols(3, 2);
    threw = false;
    try {
        layer.pinball_loss(pred, y_wrong_cols);
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "an (N, K) y must throw -- y is (N, 1)");

    Tensor y_wrong_rows(2, 1);
    threw = false;
    try {
        layer.pinball_loss(pred, y_wrong_rows);
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "a mismatched y row count must throw");

    threw = false;
    try {
        layer.backward(Tensor(3, 2), 0.0);
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "a mismatched grad_output shape must throw in backward");

    threw = false;
    try {
        layer.level_column(pred, 99);
    } catch (const std::exception&) {
        threw = true;
    }
    check(threw, "an out-of-range level index must throw");

    // --- the accumulation contract ---
    // The gradients ACCUMULATE across backward calls, like every other layer
    // in the repo. A caller that calls backward twice must see the SUM.
    //
    // BOTH PARAMETERS ARE CHECKED. The first draft of this test checked only
    // the BIAS gradient, and the mutation harness reported the weight
    // gradient's "assigned instead of accumulated" mutation as SURVIVED --
    // a real hole in the suite, not a false verdict.
    QuantileRegression acc(1, to_vector({0.5}));
    Tensor Xa(2, 1);
    Xa[0][0] = 1.0;
    Xa[1][0] = 2.0;
    Tensor ya(2, 1);
    ya[0][0] = 0.0;
    ya[1][0] = 0.0;
    acc.zero_grad();
    Tensor pa = acc.forward(Xa);
    Tensor ga = acc.pinball_gradient(pa, ya);
    acc.backward(ga, 0.0);
    double once = acc.bias_gradient()[0][0];
    double once_w = acc.weight_gradient()[0][0];
    acc.backward(ga, 0.0);
    double twice = acc.bias_gradient()[0][0];
    double twice_w = acc.weight_gradient()[0][0];
    check_close(twice, 2.0 * once, 1e-12,
                "the BIAS gradient accumulates across backward calls");
    check_close(twice_w, 2.0 * once_w, 1e-12,
                "the WEIGHT gradient accumulates across backward calls");

    // --- the initialisation ---
    // Every level starts at the SAME flat predictor, so a crossing in a
    // fitted model is attributable to the fit and not to the
    // initialisation.
    //
    // **THE CHECK IS ON THE SLOPES, NOT ON THE PREDICTIONS.** The first
    // draft asserted that the predictions were all zero, using an all-ZERO
    // input -- and with X = 0 the predictions are zero for ANY weights, so
    // the assertion was VACUOUS: it could not distinguish the shipped
    // all-zero initialisation from a random one. The mutation harness caught
    // it by reporting the "random initialisation" mutation as SURVIVED.
    //
    // The check below uses a NON-ZERO input, so the slopes are actually
    // exercised, and it asserts that the levels' PREDICTIONS ARE EQUAL --
    // which for a non-zero input means the slopes and the intercepts are
    // equal too.
    QuantileRegression fresh(2, to_vector({0.1, 0.5, 0.9}));
    Tensor Xf(3, 2);
    Xf[0][0] = 1.0;  Xf[0][1] = -2.0;
    Xf[1][0] = 0.5;  Xf[1][1] = 3.0;
    Xf[2][0] = -1.5; Xf[2][1] = 0.25;
    Tensor pf = fresh.forward(Xf);
    bool flat = true;
    for (size_t i = 0; i < 3; ++i)
        for (size_t k = 0; k < 3; ++k)
            if (pf[i][k] != pf[i][0]) flat = false;
    check(flat,
          "every level starts at the SAME predictor, so a crossing in a "
          "fitted model is attributable to the fit");
    // And the slopes themselves are zero.
    bool zero_slopes = true;
    for (size_t k = 0; k < 3; ++k)
        for (size_t d = 0; d < 2; ++d)
            if (fresh.weight_at(k, d) != 0.0) zero_slopes = false;
    check(zero_slopes, "every level's slope starts at zero");
    check(fresh.crossing_count(pf) == 0,
          "the initial model has no crossings");
}

