// =============================================================================
// TEST 2: the K = 1 layer is BIT-FOR-BIT the shipped QuantileLoss
//
// This is the strongest composition check available: it pins the loss, the
// gradient, the tie convention and the reduction SIMULTANEOUSLY. If any of
// the four drifts, this fails.
//
// NOTE that the shipped QuantileLoss takes an ELEMENTWISE (N, K) target,
// while this layer takes y as (N, 1). For K = 1 the two shapes coincide,
// which is exactly why K = 1 is the case to compare.
// =============================================================================

static void test_k1_equals_shipped_quantile_loss() {
    std::cout << "-- Test 2: the K = 1 layer equals the shipped QuantileLoss\n";

    QuantileRegression layer(ORC_F1_D, to_vector({0.3}));
    layer.set_weight_at(0, 0, ORC_F1_W[0]);
    layer.set_bias_at(0, ORC_F1_B[0]);
    Tensor X = make_tensor(ORC_F1_N, ORC_F1_D, ORC_F1_X);
    Tensor y = make_tensor(ORC_F1_N, 1, ORC_F1_Y);

    Tensor pred = layer.forward(X);

    // The shipped loss.
    QuantileLoss shipped(0.3);
    Tensor shipped_loss = shipped.forward(pred, y);
    Tensor shipped_grad = shipped.backward(pred, y);

    // The layer's own loss and gradient.
    Tensor own_loss = layer.pinball_loss(pred, y);
    Tensor own_grad = layer.pinball_gradient(pred, y);

    // EXACT equality -- not a tolerance. The two must agree to the last bit,
    // because they are the same arithmetic.
    check(own_loss[0][0] == shipped_loss[0][0],
          "the K = 1 layer's loss is BIT-FOR-BIT the shipped QuantileLoss");
    check_close(own_loss[0][0], ORC_F1_LOSS, 1e-14,
                "the K = 1 loss matches the oracle");

    bool grad_equal = true;
    for (size_t i = 0; i < ORC_F1_N; ++i) {
        if (own_grad[i][0] != shipped_grad[i][0]) grad_equal = false;
        check_close(own_grad[i][0], ORC_F1_GRAD[i], 1e-14,
                    "the K = 1 gradient matches the oracle");
    }
    check(grad_equal,
          "the K = 1 layer's gradient is BIT-FOR-BIT the shipped "
          "QuantileLoss");

    // And a second, INDEPENDENT confirmation: the shipped class on a
    // DIFFERENT tau, so the check is not tied to one level.
    for (double q : {0.1, 0.5, 0.9}) {
        QuantileRegression lay(1, to_vector({q}));
        lay.set_weight_at(0, 0, 0.7);
        lay.set_bias_at(0, 0.1);
        Tensor p = lay.forward(X);
        QuantileLoss s2(q);
        Tensor l2 = s2.forward(p, y);
        Tensor g2 = s2.backward(p, y);
        Tensor l1 = lay.pinball_loss(p, y);
        Tensor g1 = lay.pinball_gradient(p, y);
        check(l1[0][0] == l2[0][0],
              "the K = 1 loss equals the shipped one at tau = " +
                  std::to_string(q));
        bool eq = true;
        for (size_t i = 0; i < ORC_F1_N; ++i)
            if (g1[i][0] != g2[i][0]) eq = false;
        check(eq, "the K = 1 gradient equals the shipped one at tau = " +
                     std::to_string(q));
    }
}

