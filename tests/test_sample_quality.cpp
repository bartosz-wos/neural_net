// =============================================================================
// tests/test_sample_quality.cpp -- the PUBLIC sample-quality metrics:
// the Frechet Inception Distance, the Inception Score, and the sample
// Gaussian estimator they are built on.
//
// WHAT THIS SUITE EXISTS TO PIN
// =============================================================================
//
// The repo ships FIFTEEN generative models and NOTHING measured whether
// their samples were good. This suite pins the metrics that close that
// gap, and it pins the CONVENTIONS, because every one of them is a place
// where a plausible implementation silently returns a different number:
//
//   1. FID IS THE SQUARED FREMCHET DISTANCE. The repo's shipped
//      `frechet_distance` returns the DISTANCE. The reference FID
//      implementation returns the radicand. Measured on this file's own
//      fixture: the two differ by a factor of 2.4476. This is the single
//      most common FID implementation error in the wild.
//
//   2. THE COVARIANCE ESTIMATOR IS THE UNBIASED ONE (divide by n-1).
//      Measured: 1.6535543231203407 (unbiased) against 1.6393495915149587
//      (biased). The suite asserts BOTH the unbiased value AND that the
//      biased value DIFFERS, so the convention is a measured choice.
//
//   3. THE PRODUCT ORDER. The reference implementation evaluates
//      sqrtm(S1 @ S2); S1 @ S2 is NOT symmetric (measured asymmetry 0.0739
//      on the oracle's fixture) and its square root is COMPLEX in general.
//      The repo's shipped form is symmetric PSD. The suite asserts the
//      shipped value AND that the naive form DIFFERS.
//
//   4. FID(X, X) IS EXACTLY 0 -- the shipped routine clamps its radicand
//      at zero from below, and the square is taken AFTER that clamp.
//
//   5. THE `0 * log(0/q) = 0` CONVENTION IN THE KL. The naive expression
//      evaluates 0 * (-inf) on a one-hot fixture and produces NaN. A
//      metric that reports NaN reports nothing.
//
//   6. THE SPLIT COUNT CHANGES THE IS, so it is a pinned convention and
//      not an implementation detail.
//
//   7. THE IS OF AN IDENTICAL SET IS EXACTLY 1.0.
//
//   8. THE RANK-DEFINICIENT CASE (n < d) IS THE REALISTIC ONE, and it
//      must not throw: a sample covariance from n samples in d > n
//      dimensions has rank <= n-1 and is SINGULAR, so a Cholesky-based
//      implementation would throw on exactly the case a 2048-dimensional
//      feature space with a few hundred samples produces.
//
// THE FIXTURES ARE EMITTED, NEVER TYPED.
//
// The numbers below come from tests/sample_quality_oracle.py (float64
// numpy + scipy), which was run BEFORE this file existed. The repo has
// been burned by hand-transcribed numbers before -- both numbers were
// correct for the fixture they were given, and the fixture was simply not
// the oracle's -- so the pinned numbers are TRANSFERRED by
// tests/splice_sample_quality_fixture.py, never re-derived.
//
// THE ORACLE'S OWN SENSITIVITY IS MEASURED.
//
// tests/sample_quality_mutate_oracle.py breaks the oracle's model code in
// seventeen specific ways and requires that it FAIL each time. Its first
// run reported FOUR survivors, and every one of them was a real gap in
// the oracle rather than in the implementation -- which is why this
// suite checks ABSOLUTE values against the oracle, not just relative
// properties.
//
// THE INDEPENDENT REFERENCE.
//
// `sample_gaussian_parameters` is checked against a hand-rolled
// reference computed IN THIS FILE from the definition -- the column means
// and the centred outer sums -- so the library is not checked against
// itself. The FID's symmetrised trace term is checked against the
// reference implementation's own product order, transcribed here with
// explicit scalar loops.
// =============================================================================

