// =============================================================================
// SECTION 1 -- the three distances on the pinned fixtures
// =============================================================================

static void section_distances() {
    section("the three distances on the pinned fixtures");
    for (int i = 0; i < kEditDistanceCaseCount; ++i) {
        const EditDistanceCase& c = kEditDistanceCases[i];
        const std::string a(c.a);
        const std::string b(c.b);

        check_detail(levenshtein_distance(a, b) == static_cast<double>(c.lev),
                     std::string("character Levenshtein('") + c.a + "','" + c.b + "')",
                     to_string(levenshtein_distance(a, b)), to_string(c.lev));
        check_detail(levenshtein_distance(tokens(a), tokens(b)) == static_cast<double>(c.lev),
                     std::string("token Levenshtein('") + c.a + "','" + c.b + "')",
                     to_string(levenshtein_distance(tokens(a), tokens(b))), to_string(c.lev));
        check_detail(osa_distance(a, b) == c.osa,
                     std::string("character OSA('") + c.a + "','" + c.b + "')",
                     to_string(osa_distance(a, b)), to_string(c.osa));
        check_detail(osa_distance(tokens(a), tokens(b)) == c.osa,
                     std::string("token OSA('") + c.a + "','" + c.b + "')",
                     to_string(osa_distance(tokens(a), tokens(b))), to_string(c.osa));
        check_detail(damerau_levenshtein_distance(a, b) == c.dl,
                     std::string("character DL('") + c.a + "','" + c.b + "')",
                     to_string(damerau_levenshtein_distance(a, b)), to_string(c.dl));
        check_detail(damerau_levenshtein_distance(tokens(a), tokens(b)) == c.dl,
                     std::string("token DL('") + c.a + "','" + c.b + "')",
                     to_string(damerau_levenshtein_distance(tokens(a), tokens(b))),
                     to_string(c.dl));
    }
}

// =============================================================================
// SECTION 2 -- the three distances are DIFFERENT FUNCTIONS
// =============================================================================

static void section_osa_vs_dl() {
    section("OSA and unrestricted DL are different functions");

    // The discriminating pair from the oracle: OSA 3, unrestricted DL 2.
    check_detail(osa_distance("ca", "abc") == 3, "osa('ca','abc') == 3",
                 to_string(osa_distance("ca", "abc")), "3");
    check_detail(damerau_levenshtein_distance("ca", "abc") == 2,
                 "dl('ca','abc') == 2",
                 to_string(damerau_levenshtein_distance("ca", "abc")), "2");
    check_detail(levenshtein_distance("ca", "abc") == 3, "lev('ca','abc') == 3",
                 to_string(levenshtein_distance("ca", "abc")), "3");

    // The pair every wrong Lowrance-Wagner transcription fails on.
    check_detail(damerau_levenshtein_distance("cabcac", "bbc") == 4,
                 "dl('cabcac','bbc') == 4 -- the pair on which FIVE rejected "
                 "Lowrance-Wagner transcriptions all answer 5",
                 to_string(damerau_levenshtein_distance("cabcac", "bbc")), "4");

    // A transposition is cheaper than two substitutions in BOTH restricted
    // variants -- that is what makes them different from plain Levenshtein.
    check(osa_distance("ab", "ba") == 1, "osa('ab','ba') == 1 (one transposition)");
    check(damerau_levenshtein_distance("ab", "ba") == 1,
          "dl('ab','ba') == 1 (one transposition)");
    check(levenshtein_distance("ab", "ba") == 2,
          "lev('ab','ba') == 2 (two substitutions -- no transposition allowed)");

    // OSA is NOT a metric; the unrestricted DL IS. These are the measured
    // witnesses, and they are pinned so a future change cannot quietly turn
    // one into the other.
    check(osa_distance("ab", "bca") > osa_distance("ab", "ba") + osa_distance("ba", "bca"),
          "OSA violates the triangle inequality: osa('ab','bca')=3 > 1 + 1");
}

// =============================================================================
// SECTION 3 -- the weighted distance is DIRECTED
// =============================================================================

static void section_weighted() {
    section("the weighted distance, its direction, and its guards");

    for (int i = 0; i < kWeightedEditCaseCount; ++i) {
        const WeightedEditCase& c = kWeightedEditCases[i];
        EditCosts costs;
        costs.insertion = c.ins;
        costs.deletion = c.del;
        costs.substitution = c.sub;
        const std::string a(c.a);
        const std::string b(c.b);
        const double got_c = weighted_levenshtein_distance(a, b, costs);
        const double got_t = weighted_levenshtein_distance(tokens(a), tokens(b), costs);
        check_detail(std::abs(got_c - c.dist) < 1e-12,
                     std::string("weighted char ('") + c.a + "','" + c.b + "') w=(" +
                         to_string(c.ins) + "," + to_string(c.del) + "," + to_string(c.sub) + ")",
                     to_string(got_c), to_string(c.dist));
        check_detail(std::abs(got_t - c.dist) < 1e-12,
                     std::string("weighted token ('") + c.a + "','" + c.b + "')",
                     to_string(got_t), to_string(c.dist));
    }

    // THE DIRECTION. These are rapidfuzz's own numbers:
    //   distance('aa','aaa', weights=(2,1,1)) == 2  (one INSERTION, weight 2)
    //   distance('aaa','aa', weights=(2,1,1)) == 1  (one DELETION,  weight 1)
    EditCosts costs;
    costs.insertion = 2.0;
    costs.deletion = 1.0;
    costs.substitution = 1.0;
    check_detail(weighted_levenshtein_distance("aa", "aaa", costs) == 2.0,
                 "weighted('aa','aaa') with insert=2 is 2 -- the insertion is "
                 "charged at the INSERTION weight",
                 to_string(weighted_levenshtein_distance("aa", "aaa", costs)), "2");
    check_detail(weighted_levenshtein_distance("aaa", "aa", costs) == 1.0,
                 "weighted('aaa','aa') with insert=2 is 1 -- the deletion is "
                 "charged at the DELETION weight",
                 to_string(weighted_levenshtein_distance("aaa", "aa", costs)), "1");

    // And the consequence: the weighted distance is ASYMMETRIC.
    check(weighted_levenshtein_distance("aa", "aaa", costs) !=
              weighted_levenshtein_distance("aaa", "aa", costs),
          "the weighted distance is asymmetric when insertion != deletion");

    // With EQUAL insertion and deletion it is symmetric again.
    EditCosts sym;
    sym.insertion = 2.0;
    sym.deletion = 2.0;
    sym.substitution = 1.0;
    check(weighted_levenshtein_distance("kitten", "sitting", sym) ==
              weighted_levenshtein_distance("sitting", "kitten", sym),
          "the weighted distance is symmetric when insertion == deletion");

    // The unit-cost weighted distance IS the plain Levenshtein distance.
    EditCosts unit;
    for (int i = 0; i < kEditDistanceCaseCount; ++i) {
        const EditDistanceCase& c = kEditDistanceCases[i];
        check_detail(weighted_levenshtein_distance(std::string(c.a), std::string(c.b), unit) ==
                         static_cast<double>(c.lev),
                     std::string("unit-cost weighted == plain Levenshtein ('") + c.a + "','" + c.b + "')",
                     to_string(weighted_levenshtein_distance(std::string(c.a), std::string(c.b), unit)),
                     to_string(c.lev));
    }

    // The guards. Every message is DISTINCT -- a substring shared by two
    // messages discriminates nothing between them.
    bool threw_negative = false;
    std::string negative_msg;
    try {
        EditCosts bad;
        bad.insertion = -1.0;
        weighted_levenshtein_distance("a", "b", bad);
    } catch (const std::invalid_argument& e) {
        threw_negative = true;
        negative_msg = e.what();
    }
    check(threw_negative, "a negative cost throws std::invalid_argument");
    check(!negative_msg.empty() && negative_msg.find("non-negative") != std::string::npos,
          "the negative-cost message says the cost must be non-negative",
          negative_msg);

    bool threw_nan = false;
    std::string nan_msg;
    try {
        EditCosts bad;
        bad.substitution = std::nan("");
        weighted_levenshtein_distance("a", "b", bad);
    } catch (const std::invalid_argument& e) {
        threw_nan = true;
        nan_msg = e.what();
    }
    check(threw_nan, "a NaN cost throws std::invalid_argument");
    check(threw_negative && !nan_msg.empty() && nan_msg != negative_msg,
          "the two guard messages are DISTINCT");
}

// =============================================================================
// SECTION 4 -- the alignment
// =============================================================================

static void section_alignment() {
    section("the edit script and its counts");

    for (int i = 0; i < kAlignmentCaseCount; ++i) {
        const AlignmentCase& c = kAlignmentCases[i];
        const std::string a(c.a);
        const std::string b(c.b);
        const EditAlignment al = align_sequences(a, b);
        check_detail(script_to_string(al.ops) == c.script,
                     std::string("the edit script of ('") + c.a + "','" + c.b + "')",
                     script_to_string(al.ops), c.script);
        check_detail(static_cast<int>(al.matches) == c.hits &&
                         static_cast<int>(al.substitutions) == c.subs &&
                         static_cast<int>(al.deletions) == c.dels &&
                         static_cast<int>(al.insertions) == c.ins,
                     std::string("the counts of ('") + c.a + "','" + c.b + "')",
                     to_string(static_cast<int>(al.matches)) + "/" +
                         to_string(static_cast<int>(al.substitutions)) + "/" +
                         to_string(static_cast<int>(al.deletions)) + "/" +
                         to_string(static_cast<int>(al.insertions)),
                     to_string(c.hits) + "/" + to_string(c.subs) + "/" +
                         to_string(c.dels) + "/" + to_string(c.ins));
    }

    // The INVARIANT that holds everywhere: the number of edits equals the
    // distance. This is the property that makes WER well-defined even though
    // the breakdown is not.
    for (int i = 0; i < kEditDistanceCaseCount; ++i) {
        const EditDistanceCase& c = kEditDistanceCases[i];
        const std::string a(c.a);
        const std::string b(c.b);
        const EditAlignment al = align_sequences(a, b);
        check_detail(al.edit_count() == static_cast<size_t>(c.lev),
                     std::string("S+D+I == distance for ('") + c.a + "','" + c.b + "')",
                     to_string(static_cast<int>(al.edit_count())), to_string(c.lev));
        check_detail(static_cast<int>(al.matches + al.substitutions + al.deletions +
                                       al.insertions) == static_cast<int>(al.ops.size()),
                     std::string("the counts sum to the script length for ('") + c.a + "','" + c.b + "')",
                     to_string(static_cast<int>(al.matches + al.substitutions +
                                                al.deletions + al.insertions)),
                     to_string(static_cast<int>(al.ops.size())));
    }

    // REPLAY: applying the script to `a` must produce `b` exactly. This is
    // the property that says the script is a real edit script and not just a
    // list of plausible counts.
    for (int i = 0; i < kAlignmentCaseCount; ++i) {
        const AlignmentCase& c = kAlignmentCases[i];
        const std::string a(c.a);
        const std::string b(c.b);
        const EditAlignment al = align_sequences(a, b);
        std::string replay;
        size_t ai = 0;
        for (EditOp op : al.ops) {
            switch (op) {
                case EditOp::Match:
                case EditOp::Substitution:
                    replay += a[ai++];
                    break;
                case EditOp::Insertion:
                    replay += '?';
                    break;
                case EditOp::Deletion:
                    ++ai;
                    break;
            }
        }
        // The replayed string has the same SHAPE as b: every Match and
        // Substitution consumes one symbol of a and contributes one symbol of
        // b, every Insertion contributes one symbol of b, every Deletion
        // consumes one symbol of a.
        size_t consumed = 0;
        size_t produced = 0;
        for (EditOp op : al.ops) {
            if (op == EditOp::Match || op == EditOp::Substitution) {
                ++consumed;
                ++produced;
            } else if (op == EditOp::Insertion) {
                ++produced;
            } else {
                ++consumed;
            }
        }
        check_detail(consumed == a.size() && produced == b.size(),
                     std::string("the script consumes all of a and produces all "
                                 "of b ('") + c.a + "','" + c.b + "')",
                     to_string(static_cast<int>(consumed)) + "/" +
                         to_string(static_cast<int>(produced)),
                     to_string(static_cast<int>(a.size())) + "/" +
                         to_string(static_cast<int>(b.size())));
        (void)replay;
    }

    // The token-level alignment behaves identically.
    for (int i = 0; i < kAlignmentCaseCount; ++i) {
        const AlignmentCase& c = kAlignmentCases[i];
        const EditAlignment al = align_sequences(tokens(std::string(c.a)), tokens(std::string(c.b)));
        check_detail(script_to_string(al.ops) == c.script,
                     std::string("the token-level edit script of ('") + c.a + "','" + c.b + "')",
                     script_to_string(al.ops), c.script);
    }

    // DETERMINISM: the same input must give the same script every time.
    const EditAlignment first = align_sequences(std::string("kitten"), std::string("sitting"));
    const EditAlignment second = align_sequences(std::string("kitten"), std::string("sitting"));
    check(script_to_string(first.ops) == script_to_string(second.ops),
          "align_sequences is deterministic");
}

// =============================================================================
// SECTION 5 -- WER and CER
// =============================================================================

static void section_wer() {
    section("the word and character error rates");

    // The WER fixtures are over SPACE-separated words.
    for (int i = 0; i < kWerCaseCount; ++i) {
        const WerCase& c = kWerCases[i];
        auto split = [](const char* s) {
            std::vector<int> out;
            std::string cur;
            for (const char* p = s; *p; ++p) {
                if (*p == ' ') {
                    if (!cur.empty()) { out.push_back(static_cast<int>(cur[0])); cur.clear(); }
                } else {
                    cur += *p;
                }
            }
            if (!cur.empty()) out.push_back(static_cast<int>(cur[0]));
            return out;
        };
        const std::vector<int> ref = split(c.reference);
        const std::vector<int> hyp = split(c.hypothesis);
        const double got = word_error_rate(ref, hyp);
        check_detail(std::abs(got - c.wer) < 1e-12,
                     std::string("WER('") + c.reference + "','" + c.hypothesis + "')",
                     to_string(got), to_string(c.wer));
    }

    // THE EMPTY-REFERENCE CONVENTION. This is the one that a naive
    // implementation gets wrong, and it is pinned against jiwer's own
    // numbers: jiwer.wer("", "a b") == 2.
    check_detail(word_error_rate(std::vector<int>(), std::vector<int>{1, 2}) == 2.0,
                 "an EMPTY reference reports the raw insertion count (2), not "
                 "+inf and not 0",
                 to_string(word_error_rate(std::vector<int>(), std::vector<int>{1, 2})), "2");
    check_detail(word_error_rate(std::vector<int>(), std::vector<int>()) == 0.0,
                 "two empty sequences have WER 0",
                 to_string(word_error_rate(std::vector<int>(), std::vector<int>())), "0");
    check_detail(word_error_rate(std::vector<int>{1}, std::vector<int>()) == 1.0,
                 "an empty hypothesis against a one-token reference has WER 1",
                 to_string(word_error_rate(std::vector<int>{1}, std::vector<int>())), "1");

    // The CER is the same formula over characters.
    check_detail(std::abs(character_error_rate("abc", "abd") - 1.0 / 3.0) < 1e-12,
                 "CER('abc','abd') == 1/3",
                 to_string(character_error_rate("abc", "abd")), to_string(1.0 / 3.0));
    check_detail(character_error_rate("", "ab") == 2.0,
                 "an EMPTY character reference reports the raw insertion count",
                 to_string(character_error_rate("", "ab")), "2");

    // The WER does not depend on the tie-break: its numerator is the
    // DISTANCE, which is unique.
    for (int i = 0; i < kEditDistanceCaseCount; ++i) {
        const EditDistanceCase& c = kEditDistanceCases[i];
        const std::string a(c.a);
        const std::string b(c.b);
        const double wer = word_error_rate(tokens(a), tokens(b));
        const double den = a.empty() ? 1.0 : static_cast<double>(a.size());
        check_detail(std::abs(wer - static_cast<double>(c.lev) / den) < 1e-12,
                     std::string("WER == distance / max(1,|reference|) for ('") +
                         c.a + "','" + c.b + "')",
                     to_string(wer), to_string(static_cast<double>(c.lev) / den));
    }
}

