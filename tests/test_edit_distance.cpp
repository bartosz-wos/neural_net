static int g_pass = 0;
static int g_fail = 0;

static void check(bool cond, const std::string& what, const std::string& detail = "") {
    if (cond) {
        ++g_pass;
    } else {
        ++g_fail;
        std::cout << "  FAIL: " << what;
        if (!detail.empty()) std::cout << "  -- " << detail;
        std::cout << std::endl;
    }
}

static void check_detail(bool cond, const std::string& what,
                         const std::string& got, const std::string& want) {
    check(cond, what, "got '" + got + "', want '" + want + "'");
}

static void section(const char* title) {
    std::cout << std::endl << "--- " << title << " ---" << std::endl;
}

static std::string to_string(double v) {
    char buf[64];
    std::snprintf(buf, sizeof(buf), "%.10g", v);
    return std::string(buf);
}

static std::string to_string(int v) { return std::to_string(v); }

// A token sequence, so the TOKEN-LEVEL API is exercised on the same
// fixtures as the character-level one.
static std::vector<int> tokens(const std::string& s) {
    std::vector<int> out;
    for (char c : s) out.push_back(static_cast<int>(c));
    return out;
}

static std::string script_to_string(const std::vector<EditOp>& ops) {
    std::string out;
    for (EditOp op : ops) {
        switch (op) {
            case EditOp::Match: out += 'M'; break;
            case EditOp::Substitution: out += 'S'; break;
            case EditOp::Insertion: out += 'I'; break;
            case EditOp::Deletion: out += 'D'; break;
        }
    }
    return out;
}

