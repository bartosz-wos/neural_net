// SECTION 6 -- the metric properties, measured
// =============================================================================

static void section_metrics() {
    section("the metric properties");

    // The unit-cost Levenshtein distance IS a metric: symmetric, and it
    // satisfies the triangle inequality. The unrestricted DL is too. OSA is
    // NOT.
    check(levenshtein_distance("abc", "abd") == levenshtein_distance("abd", "abc"),
          "the Levenshtein distance is symmetric");
    check(damerau_levenshtein_distance("abc", "abd") == damerau_levenshtein_distance("abd", "abc"),
          "the unrestricted DL distance is symmetric");
    check(osa_distance("abc", "abd") == osa_distance("abd", "abc"),
          "the OSA distance is symmetric");

    // The triangle inequality, on a spread of triples.
    int lev_violations = 0;
    int dl_violations = 0;
    int osa_violations = 0;
    const char* pool[] = {"ab", "ba", "abc", "acb", "bca", "abbca", "aca", "caa"};
    for (const char* x : pool) {
        for (const char* y : pool) {
            for (const char* z : pool) {
                if (levenshtein_distance(x, z) >
                    levenshtein_distance(x, y) + levenshtein_distance(y, z)) ++lev_violations;
                if (damerau_levenshtein_distance(x, z) >
                    damerau_levenshtein_distance(x, y) + damerau_levenshtein_distance(y, z)) {
                    ++dl_violations;
                }
                if (osa_distance(x, z) > osa_distance(x, y) + osa_distance(y, z)) ++osa_violations;
            }
        }
    }
    check(lev_violations == 0, "the Levenshtein distance satisfies the triangle inequality",
          to_string(lev_violations) + " violations");
    check(dl_violations == 0, "the unrestricted DL distance satisfies the triangle inequality",
          to_string(dl_violations) + " violations");
    check(osa_violations > 0, "the OSA distance VIOLATES the triangle inequality (it is not a metric)",
          to_string(osa_violations) + " violations");

    // The identity and non-negativity.
    check(levenshtein_distance("abc", "abc") == 0.0, "the distance of a sequence from itself is 0");
    check(levenshtein_distance("", "") == 0.0, "the distance of two empty sequences is 0");
    check(levenshtein_distance("abc", "") == 3.0, "the distance from a 3-symbol sequence to empty is 3");
    check(levenshtein_distance("", "abc") == 3.0, "the distance from empty to a 3-symbol sequence is 3");
}

