// =============================================================================
// tests/test_edit_distance.cpp -- the edit distance utilities.
//
// THE SPECIFICATION IS tests/edit_distance_oracle.py, which was written and
// run BEFORE this file existed. Its discriminating power was MEASURED, not
// narrated: tests/edit_distance_mutate_oracle.py breaks the oracle in
// fourteen specific ways and requires that it fail each time (13 caught, 1
// documented survivor).
//
// The oracle is cross-checked against FOUR maintained references -- rapidfuzz
// (Levenshtein, weighted Levenshtein, OSA, DamerauLevenshtein, editops),
// jellyfish (Damerau-Levenshtein), and jiwer 4.0.0 (wer, cer,
// process_words) -- AND against TWO DEFINITION-LEVEL ORACLES that share no
// structure with the implementation: a breadth-first search over the STRING
// STATE SPACE, and an exhaustive enumeration of every monotone alignment.
//
// THE PINNED FIXTURES ARE TRANSFERRED FROM THE ORACLE, NOT HAND-TRANSCRIBED.
// =============================================================================
//
// THE FOUR SEMANTICS THIS SUITE EXISTS TO PIN
// =============================================================================
//
//  1. THE WEIGHTED DISTANCE IS DIRECTED. `EditCosts` describes the cost of
//     transforming `a` INTO `b`. With insertion != deletion the result is
//     asymmetric, and the boundary conditions are where that lives.
//
//  2. THE DISTANCE IS UNIQUE; THE EDIT-COUNT BREAKDOWN IS NOT. 260 of 2000
//     random pairs admit several optimal (S,D,I) splits. So the breakdown is
//     pinned ONLY where it is unique, and the INVARIANT
//     `S + D + I == distance` is pinned everywhere.
//
//  3. OSA AND UNRESTRICTED DL ARE DIFFERENT FUNCTIONS: "ca" -> "abc" is 3 for
//     OSA and 2 for unrestricted DL.
//
//  4. THE UNRESTRICTED DL RECURRENCE IS THE SENTINEL-LAYOUT ONE. Five other
//     transcriptions were measured against rapidfuzz and jellyfish and all
//     five disagreed (see the header for the table). They all fail on the
//     SAME pair, ('cabcac','bbc'), where the reference says 4.
//
// =============================================================================

