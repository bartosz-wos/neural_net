import numpy as np

# Reproduce the oracle's SECTION 1 fixture EXACTLY, and emit C++ literals.
# The first attempt at tests/test_sinkhorn.cpp hand-transcribed plausible
# numbers instead of these, so the oracle's PINNED VALUES did not transfer:
# OT_eps(a,a) came out -0.350050 where the oracle says -0.147296, and the
# tiny-displacement divergence came out 2.1e-5 where the oracle says 3.0e-6.
# Both C++ numbers were CORRECT for the fixture they were given; the fixture
# was simply not the oracle's. Pinned numbers transfer only across an
# identical fixture, so emit the real one.

# The oracle consumes `rng` sequentially: section 1 draws X then Y, and
# sections 3-5 draw more. Reproduce from the top.
rng = np.random.default_rng(20261020)
X = rng.normal(size=(7, 3))
Y = rng.normal(size=(5, 3)) + 0.4
n, m = X.shape[0], Y.shape[0]
a = np.full(n, 1.0 / n)
b = np.full(m, 1.0 / m)


def cpp_tensor(name, arr, fmt="{:+.17g}"):
    flat = arr.reshape(-1)
    body = ", ".join(fmt.format(v) for v in flat)
    print(f"Tensor {name} = Tensor({arr.shape[0]}, {arr.shape[1]}, std::vector<double>{{{body}}}.data());")


print("// ==== generated by tests/_dump_fixture.py; do not hand-edit ====")
cpp_tensor("X_FIX", X)
cpp_tensor("Y_FIX", Y)

# The tiny-displacement fixture: oracle section 3 uses Ynear = X + 1e-3*ones(3).
Ynear = X + 1e-3 * np.ones(X.shape[1])
cpp_tensor("YNEAR_FIX", Ynear, fmt="{:+.17g}")

# Re-verify the two pinned values on THIS fixture so the emitted constants are
# known-correct before anyone copies them into a test.
import ast, pathlib
SRC = pathlib.Path("/home/stefan/neural_net/tests/sinkhorn_oracle.py").read_text()
tree = ast.parse(SRC)
ns = {"np": np}
exec("\n".join(ast.get_source_segment(SRC, node) for node in tree.body
             if isinstance(node, ast.FunctionDef)), ns)
sinkhorn_log, sinkhorn_divergence, sqdist, ot_eps = (
    ns["sinkhorn_log"], ns["sinkhorn_divergence"], ns["sqdist"], ns["ot_eps"])

Cxx = sqdist(X, X)
Pxx = sinkhorn_log(Cxx, a, a, 0.05, n_iter=200000, tol=1e-14)[0]
print(f"\n// OT_eps(a,a) at eps=0.05 on THIS fixture = {ot_eps(Pxx, Cxx, 0.05):.15f}")

Cxy_n, Cyy_n = sqdist(X, Ynear), sqdist(Ynear, Ynear)
Pxy_n = sinkhorn_log(Cxy_n, a, a, 0.05, n_iter=200000, tol=1e-14)[0]
Pyy_n = sinkhorn_log(Cyy_n, a, a, 0.05, n_iter=200000, tol=1e-14)[0]
plain = ot_eps(Pxy_n, Cxy_n, 0.05)
deb = plain - 0.5 * ot_eps(Pxx, Cxx, 0.05) - 0.5 * ot_eps(Pyy_n, Cyy_n, 0.05)
print(f"// plain OT_eps(X, X+1e-3) = {plain:.15f}")
print(f"// debiased S_eps(X, X+1e-3) = {deb:.15e}   ratio = {abs(deb / plain):.3e}")
print(f"// |delta|^2 = {3 * 1e-3 ** 2:.15e}  (the eps->0 prediction)")
