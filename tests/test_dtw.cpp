static int g_pass = 0;
static int g_fail = 0;

static void check(bool cond, const std::string& what, const std::string& detail = "") {
    if (cond) {
        ++g_pass;
    } else {
        ++g_fail;
        std::cout << "  FAIL: " << what;
        if (!detail.empty()) std::cout << "  -- " << detail;
        std::cout << std::endl;
    }
}

static void check_detail(bool cond, const std::string& what,
                         const std::string& got, const std::string& want) {
    check(cond, what, "got '" + got + "', want '" + want + "'");
}

static void section(const char* title) {
    std::cout << std::endl << "--- " << title << " ---" << std::endl;
}

static std::string to_string(double v) {
    char buf[64];
    std::snprintf(buf, sizeof(buf), "%.12g", v);
    return std::string(buf);
}

// A (T, D) series: T time steps, each a D-dimensional observation.
static Tensor series(const std::vector<double>& values, size_t dim) {
    const size_t T = values.size() / dim;
    Tensor t(T, dim);
    for (size_t i = 0; i < T; ++i) {
        for (size_t k = 0; k < dim; ++k) {
            t(i, k) = values[i * dim + k];
        }
    }
    return t;
}

