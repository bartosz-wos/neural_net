// SECTION 5 -- the metric properties
// =============================================================================

static void section_metrics() {
    section("DTW is symmetric but NOT a metric");

    const std::vector<std::vector<double>> pool = {
        {0.0}, {1.0}, {0.0, 1.0}, {1.0, 0.0}, {0.0, 1.0, 2.0}, {2.0, 1.0, 0.0},
    };

    int asym = 0;
    for (const auto& x : pool) {
        for (const auto& y : pool) {
            if (std::abs(dtw_distance(series(x, 1), series(y, 1)) -
                         dtw_distance(series(y, 1), series(x, 1))) > 1e-9) {
                ++asym;
            }
        }
    }
    check(asym == 0, "the DTW distance is SYMMETRIC", std::to_string(asym) + " asymmetric pairs");

    // The triangle inequality FAILS -- so DTW is not a metric, and the
    // header must not call it one.
    int viol = 0;
    for (const auto& x : pool) {
        for (const auto& y : pool) {
            for (const auto& z : pool) {
                const double a = dtw_distance(series(x, 1), series(y, 1));
                const double b = dtw_distance(series(x, 1), series(z, 1));
                const double c = dtw_distance(series(z, 1), series(y, 1));
                if (b > a + c + 1e-9) ++viol;
            }
        }
    }
    check(viol > 0, "the DTW distance VIOLATES the triangle inequality (it is not a metric)",
          std::to_string(viol) + " violations");
}

