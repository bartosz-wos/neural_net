static void section_distance() {
    section("the DTW distance on the pinned fixtures");
    for (int i = 0; i < kDtwCaseCount; ++i) {
        const DtwCase& c = kDtwCases[i];
        std::vector<double> xv, yv;
        switch (i) {
            case 0: xv = {0.0, 1.0, 2.0}; yv = {0.0, 1.0, 2.0}; break;
            case 1: xv = {0.0, 1.0, 2.0}; yv = {0.0, 2.0, 4.0}; break;
            case 2: xv = {0.0, 1.0, 2.0}; yv = {2.0, 1.0, 0.0}; break;
            case 3: xv = {0.0, 10.0}; yv = {0.0, 0.0}; break;
            case 4: xv = {1.0}; yv = {1.0}; break;
            case 5: xv = {1.0}; yv = {2.0}; break;
            case 6: xv = {0.0, 1.0, 2.0, 3.0}; yv = {0.0, 3.0, 6.0}; break;
            case 7: xv = {0.0, 0.0}; yv = {0.0, 0.0}; break;
            case 8: xv = {3.0, 1.0, 2.0}; yv = {1.0, 2.0, 3.0}; break;
            case 9: xv = {0.0, 5.0, 0.0}; yv = {0.0, 0.0, 5.0}; break;
            case 10: xv = {0.0, 0.0, 1.0, 1.0}; yv = {0.0, 0.0, 1.0, 1.0}; break;
            case 11: xv = {0.0, 0.0, 1.0, 1.0, 2.0, 2.0};
                     yv = {0.0, 0.0, 2.0, 2.0, 4.0, 4.0}; break;
            case 12: xv = {0.0, 0.0, 1.0, 1.0}; yv = {1.0, 1.0, 2.0, 2.0}; break;
            case 13: xv = {0.0, 0.0, 0.0, 1.0, 1.0, 1.0, 2.0, 2.0, 2.0};
                     yv = {3.0, 3.0, 3.0, 1.0, 1.0, 1.0, 0.0, 0.0, 0.0}; break;
            default: break;
        }
        const Tensor x = series(xv, static_cast<size_t>(c.dim));
        const Tensor y = series(yv, static_cast<size_t>(c.dim));
        const double got = dtw_distance(x, y);
        check_detail(std::abs(got - c.dist) < 1e-9,
                     "DTW distance on fixture " + std::to_string(i),
                     to_string(got), to_string(c.dist));
    }
}

// =============================================================================
// SECTION 2 -- the band
// =============================================================================

static void section_band() {
    section("the Sakoe-Chiba band");

    // The band fixtures use the series x = [0,1,2,...] against
    // y = [0,3,6,...] (or the shorter/longer variants), which is where the
    // band actually bites.
    for (int i = 0; i < kDtwBandCaseCount; ++i) {
        const DtwBandCase& c = kDtwBandCases[i];
        std::vector<double> xv, yv;
        switch (i) {
            case 0: case 1: case 2: case 3:
                xv = {0.0, 1.0, 2.0}; yv = {0.0, 2.0, 4.0}; break;
            case 4: case 5: case 6:
                xv = {0.0, 1.0, 2.0, 3.0}; yv = {0.0, 3.0, 6.0}; break;
            case 7: case 8:
                xv = {0.0, 1.0}; yv = {0.0, 1.0, 2.0}; break;
            case 9: case 10:
                xv = {0.0, 1.0, 2.0}; yv = {0.0, 1.0}; break;
            case 11: case 12:
                xv = {0.0, 1.0}; yv = {0.0, 1.0, 2.0, 3.0}; break;
            case 13:
                xv = {0.0, 1.0}; yv = {0.0, 1.0, 2.0, 3.0, 4.0}; break;
            default: break;
        }
        const Tensor x = series(xv, 1);
        const Tensor y = series(yv, 1);
        const double got = dtw_distance(x, y, c.band);
        const bool got_inf = !std::isfinite(got);
        const bool want_inf = !std::isfinite(c.dist);
        if (got_inf != want_inf) {
            check(false, "banded DTW distance on fixture " + std::to_string(i),
                  "got " + to_string(got) + ", want " + to_string(c.dist));
        } else if (!got_inf) {
            check_detail(std::abs(got - c.dist) < 1e-9,
                         "banded DTW distance on fixture " + std::to_string(i),
                         to_string(got), to_string(c.dist));
        } else {
            check(true, "banded DTW distance on fixture " + std::to_string(i));
        }
    }

    // A band that admits no path is an INFEASIBLE REQUEST, and the answer
    // is +inf -- not a large finite distance.
    const Tensor x = series({0.0, 1.0}, 1);
    const Tensor y = series({0.0, 1.0, 2.0, 3.0, 4.0}, 1);
    check(!std::isfinite(dtw_distance(x, y, 1)),
          "a band of 1 against series of length 2 and 5 admits no path and "
          "returns +inf");

    // The band must actually CONSTRAIN: a wider band never costs MORE.
    const Tensor a = series({0.0, 1.0, 2.0, 3.0}, 1);
    const Tensor b = series({0.0, 3.0, 6.0}, 1);
    const double unbounded = dtw_distance(a, b);
    bool monotone = true;
    double prev = unbounded;
    for (int band = 0; band <= 4; ++band) {
        const double v = dtw_distance(a, b, band);
        if (std::isfinite(v) && v > prev + 1e-12) monotone = false;
        if (std::isfinite(v)) prev = std::min(prev, v);
    }
    check(monotone, "a wider band never costs more than a narrower one");
    check(std::abs(dtw_distance(a, b, 0) - unbounded) > 1e-12 ||
              !std::isfinite(dtw_distance(a, b, 0)),
          "the band CONSTRAINS the distance (band=0 differs from no band)");

    // The feasibility rule: a monotone path exists iff band >= |T-S|.
    bool feasible_ok = true;
    for (size_t T = 1; T <= 5; ++T) {
        for (size_t S = 1; S <= 5; ++S) {
            for (int band = 0; band <= 6; ++band) {
                std::vector<double> xv(T), yv(S);
                for (size_t i = 0; i < T; ++i) xv[i] = static_cast<double>(i);
                for (size_t j = 0; j < S; ++j) yv[j] = static_cast<double>(j);
                const bool feasible =
                    std::isfinite(dtw_distance(series(xv, 1), series(yv, 1), band));
                const bool expected = band >= static_cast<int>(T > S ? T - S : S - T);
                if (feasible != expected) feasible_ok = false;
            }
        }
    }
    check(feasible_ok, "a monotone path exists iff band >= |T-S|");

    // A negative band is a caller error.
    bool threw = false;
    std::string msg;
    try {
        dtw_distance(a, b, -1);
    } catch (const std::invalid_argument& e) {
        threw = true;
        msg = e.what();
    }
    check(threw, "a negative band throws std::invalid_argument");
    check(!msg.empty() && msg.find("non-negative") != std::string::npos,
          "the negative-band message says the band must be non-negative", msg);
}

// =============================================================================
// SECTION 3 -- the warping path
// =============================================================================

static void section_path() {
    section("the warping path");

    for (int i = 0; i < kDtwPathCaseCount; ++i) {
        const DtwPathCase& c = kDtwPathCases[i];
        std::vector<double> xv, yv;
        switch (i) {
            case 0: xv = {0.0, 1.0, 2.0}; yv = {0.0, 1.0, 2.0}; break;
            case 1: xv = {0.0, 1.0, 2.0}; yv = {0.0, 2.0, 4.0}; break;
            case 2: xv = {0.0, 1.0, 2.0}; yv = {2.0, 1.0, 0.0}; break;
            case 3: xv = {0.0, 1.0}; yv = {0.0, 0.0}; break;
            case 4: xv = {0.0, 1.0}; yv = {1.0, 2.0}; break;
            case 5: xv = {0.0, 1.0, 2.0}; yv = {0.0, 1.0}; break;
            case 6: xv = {0.0, 1.0, 2.0, 3.0}; yv = {0.0, 3.0, 6.0}; break;
            case 7: xv = {1.0}; yv = {1.0}; break;
            case 8: xv = {0.0, 0.0}; yv = {0.0, 0.0}; break;
            default: break;
        }
        const Tensor x = series(xv, 1);
        const Tensor y = series(yv, 1);
        const DtwPath p = dtw_align(x, y);

        check_detail(static_cast<int>(p.cells.size()) == c.n_path,
                     "the path length on fixture " + std::to_string(i),
                     std::to_string(static_cast<int>(p.cells.size())),
                     std::to_string(c.n_path));

        // The path's cells must be EXACTLY the oracle's.
        bool same = p.cells.size() == static_cast<size_t>(c.n_path);
        if (same) {
            for (int k = 0; k < c.n_path; ++k) {
                if (static_cast<int>(p.cells[k].first) != c.cells[2 * k] ||
                    static_cast<int>(p.cells[k].second) != c.cells[2 * k + 1]) {
                    same = false;
                    break;
                }
            }
        }
        check_detail(same, "the path's cells on fixture " + std::to_string(i),
                     same ? "match" : "differ", "match");

        // The path's cost equals the distance.
        check_detail(std::abs(p.cost - dtw_distance(x, y)) < 1e-12,
                     "the path's cost equals the distance on fixture " + std::to_string(i),
                     to_string(p.cost), to_string(dtw_distance(x, y)));
    }

    // The path is a legal monotone path: it starts at (0,0), ends at
    // (T-1,S-1), and every step advances by (1,0), (0,1) or (1,1).
    bool legal = true;
    bool covers = true;
    for (int i = 0; i < kDtwPathCaseCount; ++i) {
        const DtwPathCase& c = kDtwPathCases[i];
        std::vector<double> xv(c.n), yv(c.m);
        for (int k = 0; k < c.n; ++k) xv[k] = static_cast<double>(k);
        for (int k = 0; k < c.m; ++k) yv[k] = static_cast<double>(k);
        const DtwPath p = dtw_align(series(xv, 1), series(yv, 1));
        if (p.cells.empty()) { legal = false; continue; }
        if (p.cells.front().first != 0 || p.cells.front().second != 0) legal = false;
        if (p.cells.back().first != static_cast<size_t>(c.n - 1) ||
            p.cells.back().second != static_cast<size_t>(c.m - 1)) {
            legal = false;
        }
        for (size_t k = 0; k + 1 < p.cells.size(); ++k) {
            const long di = static_cast<long>(p.cells[k + 1].first) -
                            static_cast<long>(p.cells[k].first);
            const long dj = static_cast<long>(p.cells[k + 1].second) -
                            static_cast<long>(p.cells[k].second);
            if (!((di == 1 && dj == 0) || (di == 0 && dj == 1) || (di == 1 && dj == 1))) {
                legal = false;
            }
        }
        // The path must reach the last time step of BOTH series.
        size_t max_i = 0, max_j = 0;
        for (const auto& cell : p.cells) {
            max_i = std::max(max_i, cell.first);
            max_j = std::max(max_j, cell.second);
        }
        if (max_i != static_cast<size_t>(c.n - 1) || max_j != static_cast<size_t>(c.m - 1)) {
            covers = false;
        }
    }
    check(legal, "every path is a legal monotone path (start, end, and steps)");
    check(covers, "every path reaches the last time step of both series");

    // THE TIE-BREAK ORDER. The warping path is not unique, and the shipped
    // tie-break is ('d','l','u'): diagonal, then horizontal, then vertical.
    //
    // The path fixtures in this section all have a UNIQUE optimal path, so
    // they cannot tell one predecessor order from another. The tie fixtures
    // below can, and they are pinned separately.
    int tie_mismatches = 0;
    for (int i = 0; i < kDtwTieCaseCount; ++i) {
        const DtwTieCase& c = kDtwTieCases[i];
        std::vector<double> xv, yv;
        for (int k = 0; k < c.n; ++k) xv.push_back(static_cast<double>(c.x[k]));
        for (int k = 0; k < c.m; ++k) yv.push_back(static_cast<double>(c.y[k]));
        const DtwPath p = dtw_align(series(xv, 1), series(yv, 1));

        bool same = p.cells.size() == static_cast<size_t>(c.n_path);
        if (same) {
            for (int k = 0; k < c.n_path; ++k) {
                if (static_cast<int>(p.cells[k].first) != c.cells[2 * k] ||
                    static_cast<int>(p.cells[k].second) != c.cells[2 * k + 1]) {
                    same = false;
                    break;
                }
            }
        }
        check_detail(same, "the tie-break path on fixture " + std::to_string(i),
                     same ? "match" : "differ", "match");
        if (!same) ++tie_mismatches;
    }
    check(tie_mismatches == 0,
          "the shipped predecessor order is ('d','l','u') on every "
          "tie-discriminating fixture",
          std::to_string(tie_mismatches) + " mismatches / " +
              std::to_string(kDtwTieCaseCount) + " fixtures");

    // THE FIXTURES MUST ACTUALLY DISCRIMINATE. If every fixture had a unique
    // optimal path, the check above would pass for ANY order -- a test that
    // cannot fail. The property: each tie fixture must admit MORE THAN ONE
    // optimal path, which is exactly what makes the order observable.
    //
    // The number of optimal paths is counted by a backward dynamic program
    // over the same lattice, which is a different computation from the
    // forward one the implementation uses.
    int discriminating = 0;
    for (int i = 0; i < kDtwTieCaseCount; ++i) {
        const DtwTieCase& c = kDtwTieCases[i];
        std::vector<double> xv, yv;
        for (int k = 0; k < c.n; ++k) xv.push_back(static_cast<double>(c.x[k]));
        for (int k = 0; k < c.m; ++k) yv.push_back(static_cast<double>(c.y[k]));
        const size_t T = static_cast<size_t>(c.n);
        const size_t S = static_cast<size_t>(c.m);
        const double inf = std::numeric_limits<double>::infinity();
        std::vector<std::vector<double>> D(T + 1, std::vector<double>(S + 1, inf));
        D[0][0] = 0.0;
        for (size_t a = 1; a <= T; ++a) {
            for (size_t b = 1; b <= S; ++b) {
                const double diff = xv[a - 1] - yv[b - 1];
                D[a][b] = std::min(D[a - 1][b - 1], std::min(D[a][b - 1], D[a - 1][b])) +
                          std::sqrt(diff * diff);
            }
        }
        std::vector<std::vector<long>> ways(T + 1, std::vector<long>(S + 1, 0));
        ways[0][0] = 1;
        for (size_t a = 1; a <= T; ++a) {
            for (size_t b = 1; b <= S; ++b) {
                const double best = std::min(D[a - 1][b - 1], std::min(D[a][b - 1], D[a - 1][b]));
                long n = 0;
                if (D[a - 1][b - 1] == best) n += ways[a - 1][b - 1];
                if (D[a][b - 1] == best) n += ways[a][b - 1];
                if (D[a - 1][b] == best) n += ways[a - 1][b];
                ways[a][b] = n;
            }
        }
        if (ways[T][S] > 1) ++discriminating;
    }
    check(discriminating == kDtwTieCaseCount,
          "EVERY tie fixture admits more than one optimal path -- so the order "
          "is observable and the check above can actually fail",
          std::to_string(discriminating) + " of " + std::to_string(kDtwTieCaseCount) +
              " fixtures are tie-heavy");

    // DETERMINISM.
    const DtwPath p1 = dtw_align(series({0.0, 1.0, 2.0}, 1), series({0.0, 2.0, 4.0}, 1));
    const DtwPath p2 = dtw_align(series({0.0, 1.0, 2.0}, 1), series({0.0, 2.0, 4.0}, 1));
    check(p1.cells == p2.cells, "dtw_align is deterministic");

    // An infeasible band gives an EMPTY path and an infinite cost.
    const DtwPath infeasible = dtw_align(series({0.0, 1.0}, 1), series({0.0, 1.0, 2.0, 3.0, 4.0}, 1), 1);
    check(infeasible.cells.empty(), "an infeasible band gives an EMPTY path");
    check(!std::isfinite(infeasible.cost), "an infeasible band gives an infinite cost");
}

