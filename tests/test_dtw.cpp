// =============================================================================
// tests/test_dtw.cpp -- the dynamic time warping utilities.
//
// THE SPECIFICATION IS tests/dtw_oracle.py, which was written and run BEFORE
// this file existed. Its discriminating power was MEASURED, not narrated:
// tests/dtw_mutate_oracle.py breaks the oracle in seventeen specific ways and
// requires that it fail each time (16 caught, 1 documented survivor).
//
// The oracle checks the implementation against an EXHAUSTIVE ENUMERATION of
// every monotone path through the warping lattice -- the DEFINITION of the
// warping problem rather than an algorithm for it -- and against dtw-python
// with the step pattern pinned EXPLICITLY (dtw-python's DEFAULT is
// symmetric2, which is a different function).
//
// =============================================================================
// THE SIX SEMANTICS THIS SUITE EXISTS TO PIN
// =============================================================================
//
//  1. THE STEP PATTERN IS symmetric1 -- the three-neighbour lattice. It is
//     NOT a pattern with two-step jumps: x = [0,100] against y = [0] costs
//     100.0, where a jump-capable pattern would have cost 0.
//
//  2. THE LOCAL COST IS EUCLIDEAN, summed RAW -- not normalised by the path
//     length, not normalised by (n+m).
//
//  3. THE BAND IS |i-j| <= band ON TIME INDICES.
//
//  4. A BAND THAT ADMITS NO PATH IS AN INFEASIBLE REQUEST, not a large
//     distance: the result is +inf. A monotone path exists iff band >= |T-S|.
//
//  5. THE WARPING PATH IS NOT UNIQUE, but the shipped tie-break is
//     deterministic and reproduces dtw-python's own path on tie-heavy
//     observations.
//
//  6. DTW IS SYMMETRIC BUT NOT A METRIC -- the triangle inequality is
//     violated on a measurable fraction of random triples.
//
//  7. THE `Tensor` SHAPE IS NOT INTERCHANGEABLE HERE, unlike in
//     utils/rank_correlation.h: rows are TIME STEPS and columns are
//     DIMENSIONS. A (T,1) tensor is T scalar observations; a (1,T) tensor is
//     ONE observation of T dimensions.
//
// =============================================================================

