// SECTION 4 -- the shape convention, and the guards
// =============================================================================

static void section_shape_and_guards() {
    section("the shape convention and the guards");

    // THE SHAPE IS NOT INTERCHANGEABLE HERE, unlike in utils/rank_correlation.h.
    // A (T,1) tensor is T scalar observations; a (1,T) tensor is ONE
    // observation of T dimensions.
    //
    // The SAME flat values, arranged differently, give DIFFERENT answers:
    //   as three scalar observations [0],[1],[2] against [0],[2],[4] -> 3.0
    //   as one 3-D observation [0,1,2] against [0,2,4]               -> 2.236
    // A module that inherited the sibling modules' "the values are what
    // matter" convention would compute one of these for both.
    Tensor as_series(3, 1);
    as_series(0, 0) = 0.0;
    as_series(1, 0) = 1.0;
    as_series(2, 0) = 2.0;
    Tensor as_series_b(3, 1);
    as_series_b(0, 0) = 0.0;
    as_series_b(1, 0) = 2.0;
    as_series_b(2, 0) = 4.0;

    Tensor as_one_observation(1, 3);
    as_one_observation(0, 0) = 0.0;
    as_one_observation(0, 1) = 1.0;
    as_one_observation(0, 2) = 2.0;
    Tensor as_one_observation_b(1, 3);
    as_one_observation_b(0, 0) = 0.0;
    as_one_observation_b(0, 1) = 2.0;
    as_one_observation_b(0, 2) = 4.0;

    const double d_series = dtw_distance(as_series, as_series_b);
    const double d_one = dtw_distance(as_one_observation, as_one_observation_b);
    check(std::abs(d_series - 3.0) < 1e-12,
          "the same flat values as three scalar observations give DTW 3.0",
          to_string(d_series));
    check(std::abs(d_one - 2.23606797749979) < 1e-9,
          "the same flat values as one 3-D observation give DTW 2.236",
          to_string(d_one));
    check(std::abs(d_series - d_one) > 1e-9,
          "a (3,1) tensor and a (1,3) tensor are DIFFERENT series -- the "
          "shape convention is load-bearing here");
    check_detail(dtw_distance(as_series, as_series) == 0.0,
                 "the distance of a (3,1) series from itself is 0",
                 to_string(dtw_distance(as_series, as_series)), "0");

    // A (T,1) series is T scalar observations, so its distance is the
    // ordinary one-dimensional DTW.
    check(std::abs(dtw_distance(as_series, as_series)) < 1e-12,
          "a (T,1) tensor behaves as T scalar observations");

    // THE POINT OF DTW: the same trajectory, sampled differently. The DTW
    // distance is 0 while the plain L2 distance is 3.16.
    const Tensor shifted_x = series({0.0, 0.0, 0.0, 1.0, 2.0, 3.0}, 1);
    const Tensor shifted_y = series({0.0, 1.0, 2.0, 3.0, 3.0, 3.0}, 1);
    check_detail(std::abs(dtw_distance(shifted_x, shifted_y)) < 1e-12,
                 "the same trajectory sampled differently has DTW 0",
                 to_string(dtw_distance(shifted_x, shifted_y)), "0");

    // The guards. Every message is DISTINCT.
    bool threw_empty_x = false;
    std::string msg_x;
    try {
        dtw_distance(Tensor(0, 1), as_series);
    } catch (const std::invalid_argument& e) {
        threw_empty_x = true;
        msg_x = e.what();
    }
    check(threw_empty_x, "an empty x series throws std::invalid_argument");

    bool threw_empty_y = false;
    std::string msg_y;
    try {
        dtw_distance(as_series, Tensor(0, 1));
    } catch (const std::invalid_argument& e) {
        threw_empty_y = true;
        msg_y = e.what();
    }
    check(threw_empty_y, "an empty y series throws std::invalid_argument");
    check(threw_empty_x && !msg_x.empty() && msg_x != msg_y,
          "the two empty-series guard messages are DISTINCT");

    bool threw_dim = false;
    std::string msg_dim;
    try {
        dtw_distance(series({0.0, 1.0}, 1), series({0.0, 1.0}, 2));
    } catch (const std::invalid_argument& e) {
        threw_dim = true;
        msg_dim = e.what();
    }
    check(threw_dim, "mismatched dimensions throw std::invalid_argument");
    check(threw_dim && !msg_dim.empty() && msg_dim != msg_x && msg_dim != msg_y,
          "the dimension-mismatch message is DISTINCT from the others");
    check(!msg_dim.empty() && msg_dim.find("dimension") != std::string::npos,
          "the dimension-mismatch message says the dimensions differ", msg_dim);
}

